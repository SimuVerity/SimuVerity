function values = simuverity_public_nominal_inputs_remaining58( ...
        benchmarkTaskId, publicNames)
%SIMUVERITY_PUBLIC_NOMINAL_INPUTS_REMAINING58 Nominal-input provider.
% Eight project-backed inputs are loaded from the adjacent public MAT
% bundle. XFLUID-08 uses its task-specific nominal input policy. All other
% tasks delegate to the adjacent core provider.

benchmarkTaskId = string(benchmarkTaskId);
publicNames = unique(string(publicNames(:)), "stable");
publicNames(publicNames == "") = [];

runtimeRoot = string(fileparts(mfilename("fullpath")));
v1Path = fullfile(runtimeRoot, ...
    "simuverity_public_nominal_inputs_remaining58_core.m");
bundlePath = fullfile(runtimeRoot, ...
    "simuverity_public_nominal_inputs_remaining58_fixture.mat");
localRequireFile(v1Path, "CoreProvider");

bundleTaskIds = [ ...
    "XBATT-06"; "XBATT-09"; "XCOMM-02"; ...
    "XMECH-03"; "XMED-08"; "XROBO-04"; ...
    "XROBO-07"; "XROBO-09"];
if benchmarkTaskId == "XFLUID-08"
    localRequireNames(publicNames, ["flight_fuel_command"; ...
        "initial_fuel_volume_m3"]);
    time = [0.0; 3000.0];
    command = repmat([0.0, 0.0, 120.0, 120.0, 120.0, 120.0], 2, 1);
    values = struct( ...
        "flight_fuel_command", timeseries(command, time), ...
        "initial_fuel_volume_m3", [10.0, 10.0, 5.0]);
elseif any(benchmarkTaskId == bundleTaskIds)
    localRequireFile(bundlePath, "FixtureBundle");
    payload = load(bundlePath, "fixtureBundle");
    bundle = payload.fixtureBundle;
    assert(string(bundle.schema) == ...
        "simuverity.public-nominal-fixture-bundle.v1" && ...
        double(bundle.task_count) == 8, ...
        "SimuVerity:CandidateClosure:Remaining58BundleContract", ...
        "The published evaluator fixture bundle has the wrong schema or count.");
    rowIds = string({bundle.tasks.benchmark_task_id}).';
    rowIndex = find(rowIds == benchmarkTaskId);
    assert(isscalar(rowIndex), ...
        "SimuVerity:CandidateClosure:Remaining58BundleTask", ...
        "The published evaluator fixture bundle lacks one exact task row.");
    expectedNames = string(bundle.tasks(rowIndex).public_input_names(:));
    localRequireNames(publicNames, expectedNames);
    values = bundle.tasks(rowIndex).values;
    assert(isstruct(values) && isscalar(values) && ...
        isequal(sort(string(fieldnames(values))), sort(expectedNames)), ...
        "SimuVerity:CandidateClosure:Remaining58BundleValueContract", ...
        "The evaluator-owned fixture row violates its public-name contract.");
else
    values = simuverity_public_nominal_inputs_remaining58_core( ...
        benchmarkTaskId, publicNames);
end
end

function localRequireNames(actual, expected)
actual = sort(string(actual(:)));
expected = sort(string(expected(:)));
assert(isequal(actual, expected), ...
    "SimuVerity:CandidateClosure:Remaining58PublicNominalInputContract", ...
    "Evaluator-owned nominal input names do not match the public contract.");
end

function localRequireFile(pathValue, role)
assert(isfile(pathValue), ...
    "SimuVerity:CandidateClosure:Remaining58RuntimeFileMissing", ...
    "The staged %s file is missing.", role);
end
