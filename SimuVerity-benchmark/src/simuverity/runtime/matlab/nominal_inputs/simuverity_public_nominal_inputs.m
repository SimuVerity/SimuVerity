function values = simuverity_public_nominal_inputs(benchmarkTaskId, publicNames)
%SIMUVERITY_PUBLIC_NOMINAL_INPUTS SimuVerity 101-task nominal-input dispatcher.
% This evaluator-owned entry point is used only after the Agent exits.  It
% dispatches to release-bound collection components, never reads the Agent
% workspace, and fails closed for unsupported or authority-blocked tasks.

benchmarkTaskId = string(benchmarkTaskId);
assert(isscalar(benchmarkTaskId) && strlength(benchmarkTaskId) > 0, ...
    "SimuVerity:CandidateClosure:PublicNominalTaskInvalid", ...
    "The benchmark task id must be one nonempty string scalar.");
publicNames = unique(string(publicNames(:)), "stable");
publicNames(publicNames == "") = [];

first20Tasks = [ ...
    "XAERO-02"; "XAERO-03"; "XAERO-04"; ...
    "XAERO-06"; "XAERO-07"; "XAERO-08"; ...
    "XAERO-09"; "XAERO-10"; "XAERO-11"; ...
    "XAUTO-02"; "XAUTO-03"; "XAUTO-04"; ...
    "XAUTO-06"; "XAUTO-07"; "XAUTO-09"; ...
    "XAUTO-10"; "XAUTO-11"; "XBATT-02"; ...
    "XBATT-03"; "XBATT-04"];

if any(benchmarkTaskId == first20Tasks)
    values = simuverity_public_nominal_inputs_first20( ...
        benchmarkTaskId, publicNames);
elseif startsWith(benchmarkTaskId, "F90-")
    values = simuverity_public_nominal_inputs_remaining58( ...
        benchmarkTaskId, publicNames);
else
    values = simuverity_public_nominal_inputs_additional23( ...
        benchmarkTaskId, publicNames);
end

assert(isstruct(values) && isscalar(values), ...
    "SimuVerity:CandidateClosure:PublicNominalOutputInvalid", ...
    "The public nominal provider must return one scalar struct.");
assert(isequal(sort(string(fieldnames(values))), sort(publicNames)), ...
    "SimuVerity:CandidateClosure:PublicNominalMembership", ...
    "The provider must return exactly the declared public inputs.");
end
