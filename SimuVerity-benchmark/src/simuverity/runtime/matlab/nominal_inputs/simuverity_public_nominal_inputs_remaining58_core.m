function value = localXrobo09Traffic(fixturePath, stopTime)
payload = load(fixturePath);
fields = string(fieldnames(payload));
scene = [];
for field = fields.'
    candidate = payload.(char(field));
    if isa(candidate, "uavScenario")
        scene = candidate;
        break;
    end
end
assert(~isempty(scene), ...
    "SimuVerity:CandidateClosure:Remaining58Fixture", ...
    "Pinned XROBO-09 traffic fixture contains no uavScenario.");
setup(scene);
platforms = scene.Platforms;
names = strings(numel(platforms), 1);
for index = 1:numel(platforms)
    names(index) = string(platforms(index).Name);
end
traffic = find(~contains(lower(names), "ego"));
if numel(traffic) == numel(platforms) && numel(traffic) > 1
    traffic = traffic(2:end);
end
traffic = traffic(1:min(3, numel(traffic)));
nativeTime = zeros(0, 1);
nativeData = zeros(0, 18);
[nativeTime, nativeData] = localAppendTraffic( ...
    nativeTime, nativeData, double(scene.CurrentTime), platforms, traffic);
while double(scene.CurrentTime) < stopTime && advance(scene)
    [nativeTime, nativeData] = localAppendTraffic( ...
        nativeTime, nativeData, double(scene.CurrentTime), platforms, traffic);
end
[nativeTime, index] = unique(nativeTime, "stable");
nativeData = nativeData(index,:);
time = (0:0.1:stopTime).';
data = zeros(numel(time), 18);
for vessel = 1:3
    columns = (vessel-1)*6 + (1:6);
    if vessel > numel(traffic), continue; end
    valid = nativeData(:,columns(6)) > 0.5 & ...
        all(isfinite(nativeData(:,columns(1:5))), 2);
    assert(nnz(valid) >= 2);
    for channel = 1:4
        data(:,columns(channel)) = interp1(nativeTime(valid), ...
            nativeData(valid,columns(channel)), time, "linear", "extrap");
    end
    yaw = unwrap(nativeData(valid,columns(5)));
    data(:,columns(5)) = mod(interp1(nativeTime(valid), yaw, time, ...
        "linear", "extrap") + pi, 2*pi) - pi;
    data(:,columns(6)) = double(time >= nativeTime(find(valid,1)) & ...
        time <= nativeTime(find(valid,1,"last")));
end
value = timeseries(data, time);
end

function [time, data] = localAppendTraffic( ...
        time, data, current, platforms, traffic)
row = zeros(1, 18);
for vessel = 1:numel(traffic)
    motion = double(read(platforms(traffic(vessel))));
    columns = (vessel-1)*6 + (1:6);
    if numel(motion) >= 13 && all(isfinite(motion([1 2 4 5 10:13])))
        quaternion = motion(10:13);
        yaw = atan2(2*(quaternion(1)*quaternion(4) + ...
            quaternion(2)*quaternion(3)), ...
            1 - 2*(quaternion(3)^2 + quaternion(4)^2));
        row(columns) = [motion(1), motion(2), motion(4), ...
            motion(5), yaw, 1];
    end
end
time(end+1,1) = current;
data(end+1,:) = row;
end

