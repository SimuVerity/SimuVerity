function values = simuverity_public_nominal_inputs_first20(benchmarkTaskId, publicNames)
%SIMUVERITY_PUBLIC_NOMINAL_INPUTS_FIRST20 Nominal-input definitions.
% This provider is invoked by candidate closure after the Agent exits.  It
% returns public-contract nominal inputs only; it never reads the Agent base
% workspace and its values are never packaged as candidate dependencies.

benchmarkTaskId = string(benchmarkTaskId);
publicNames = unique(string(publicNames(:)), "stable");
publicNames(publicNames == "") = [];

switch benchmarkTaskId
    case "XAERO-02"
        localRequireNames(publicNames, "xaero02_input");
        baseWaypoints = [ ...
            0.0, -15.909902576697318, 31.819805153394647, 47.72970773009197; ...
            -80.0, -127.72970773009197, -111.81980515339464, -64.09009742330268; ...
            0.0, -38.97114317029974, -77.94228634059948, -38.97114317029974];
        centroid = mean(baseWaypoints, 2);
        waypoints = centroid + 1.0.*(baseWaypoints - centroid);
        values = struct("xaero02_input", struct( ...
            "waypoints_m", waypoints, ...
            "crosswind_step_mps", 0.0, ...
            "initial_airspeed_mps", 15.0));
    case "XAERO-03"
        localRequireNames(publicNames, ["altitude_reference"; ...
            "airspeed_reference"; "heading_change"; ...
            "initial_altitude_offset"; "initial_airspeed_offset"; ...
            "command_time"; "gust_speed"; "gust_heading"; "gust_time"]);
        values = struct( ...
            "altitude_reference", 3048.0, ...
            "airspeed_reference", 150.0, ...
            "heading_change", 0.30, ...
            "initial_altitude_offset", -120.0, ...
            "initial_airspeed_offset", -10.0, ...
            "command_time", 4.0, ...
            "gust_speed", 12.0, ...
            "gust_heading", 90.0, ...
            "gust_time", 9.0);
    case "XAERO-04"
        localRequireNames(publicNames, ["MissionKind"; ...
            "InitialFlightMode"; "MissionProfile"; "PayloadScale"; ...
            "EnableWind"; "SimulationDuration_s"]);
        profile = [ ...
            1, 0, 0, 0, 0, 0, 0, 0; ...
            2, 0, 0, -20, 0, 0, 0, 0; ...
            2, 20, 0, -20, 0, 0, 0, 0; ...
            2, 20, 20, -20, 0, 0, 0, 0];
        values = struct( ...
            "MissionKind", 1.0, ...
            "InitialFlightMode", 0.0, ...
            "MissionProfile", profile, ...
            "PayloadScale", 1.0, ...
            "EnableWind", false, ...
            "SimulationDuration_s", 45.0);
    case "XAERO-06"
        localRequireNames(publicNames, ["InitialAirspeedScale"; ...
            "InitialBankOffset_deg"; "VehicleMassScale"; ...
            "WindSeverityScale"]);
        values = struct( ...
            "InitialAirspeedScale", 1.0, ...
            "InitialBankOffset_deg", 0.0, ...
            "VehicleMassScale", 1.0, ...
            "WindSeverityScale", 1.0);
    case "XAERO-07"
        localRequireNames(publicNames, "aircraft_design_input");
        values = struct("aircraft_design_input", struct( ...
            "battery_capacity_Ah", 100.0, ...
            "payload_mass_kg", 0.0));
    case "XAERO-08"
        localRequireNames(publicNames, ["mass_flow_kg_per_s"; ...
            "payload_mass_kg"; "gravity_turn_angle_rad"]);
        values = struct( ...
            "mass_flow_kg_per_s", 132.0, ...
            "payload_mass_kg", 5000.0, ...
            "gravity_turn_angle_rad", 0.10);
    case "XAERO-09"
        localRequireNames(publicNames, "lunar_dap_case_input");
        values = struct("lunar_dap_case_input", struct( ...
            "attitude_command_offset_deg", [0.0; 0.0; 2.0], ...
            "initial_body_rate_deg_s", [0.573; 0.573; 6.808], ...
            "jet_count_mode", 2.0, ...
            "pitch_roll_jet_mode", 2.0, ...
            "thruster_force_scale", 1.0));
    case "XAERO-10"
        localRequireNames(publicNames, ["attitude_command_rad"; ...
            "measurement_noise_covariance"]);
        values = struct( ...
            "attitude_command_rad", 0.0, ...
            "measurement_noise_covariance", 1.0);
    case "XAERO-11"
        localRequireNames(publicNames, "adcs_case_input");
        values = struct("adcs_case_input", struct( ...
            "operation_mode", 1.0, ...
            "initial_body_rate_rad_s", [0.0; 0.0; 0.0], ...
            "target_inertial_unit_vector", [1.0; 0.0; 0.0], ...
            "sensor_noise_scale", 1.0, ...
            "disturbance_scale", 1.0));
    case "XAUTO-02"
        localRequireNames(publicNames, ["speed_reference"; ...
            "initial_speed"; "vehicle_mass"; "road_amplitude"; ...
            "road_wavelength"; "left_right_phase"; ...
            "drive_loss_fraction"; "drive_loss_time"]);
        values = struct( ...
            "speed_reference", 13.5, ...
            "initial_speed", 12.0, ...
            "vehicle_mass", 1600.0, ...
            "road_amplitude", 0.035, ...
            "road_wavelength", 3.0, ...
            "left_right_phase", 0.55, ...
            "drive_loss_fraction", 0.45, ...
            "drive_loss_time", 5.0);
    case "XAUTO-03"
        localRequireNames(publicNames, ["engine_speed_rpm"; ...
            "accessory_load_profile"]);
        time = (0:1:90).';
        engineSpeed = 900.0 + 450.0*sin(2*pi*time/90.0) + 250.0;
        accessoryLoad = 22.0 + 12.0*(mod(floor(time/15.0), 2) > 0);
        values = struct( ...
            "engine_speed_rpm", timeseries(engineSpeed, time), ...
            "accessory_load_profile", timeseries(accessoryLoad, time));
    case "XAUTO-04"
        localRequireNames(publicNames, ["TargetSpeed_mps"; ...
            "BrakeStartDistance_m"; "RequestedDeceleration_g"; ...
            "RoadFrictionScaleHigh"; "RoadFrictionScaleLow"; ...
            "UseLowFrictionPatch"; "LowFrictionPatch_m"]);
        values = struct( ...
            "TargetSpeed_mps", 20.0, ...
            "BrakeStartDistance_m", 200.0, ...
            "RequestedDeceleration_g", 0.35, ...
            "RoadFrictionScaleHigh", 0.75, ...
            "RoadFrictionScaleLow", 0.30, ...
            "UseLowFrictionPatch", false, ...
            "LowFrictionPatch_m", [150.0, -100.0, 1000.0, 200.0]);
    case "XAUTO-06"
        localRequireNames(publicNames, ["v_ref_kph"; ...
            "road_grade_pct"; "initial_soc_pct"]);
        time = (0:1:200).';
        reference = 95.0*max(0.0, sin(pi*time/200.0));
        values = struct( ...
            "v_ref_kph", timeseries(reference, time), ...
            "road_grade_pct", timeseries(zeros(size(time)), time), ...
            "initial_soc_pct", 70.0);
    case "XAUTO-07"
        localRequireNames(publicNames, "ev_drive_input");
        values = struct("ev_drive_input", struct( ...
            "acceleration_scale", 1.0, ...
            "brake_scale", 1.0));
    case "XAUTO-09"
        localRequireNames(publicNames, "lane_following_input");
        values = struct("lane_following_input", struct( ...
            "traffic_scenario", 'straight_target', ...
            "driver_set_velocity_mps", 30.0, ...
            "time_gap_s", 1.5, ...
            "default_spacing_m", 10.0));
    case "XAUTO-10"
        localRequireNames(publicNames, ["steering_angle_deg"; ...
            "rear_left_torque_nm"; "rear_right_torque_nm"]);
        values = struct( ...
            "steering_angle_deg", 0.0, ...
            "rear_left_torque_nm", 20.0, ...
            "rear_right_torque_nm", 20.0);
    case "XAUTO-11"
        localRequireNames(publicNames, "xauto11_input");
        values = struct("xauto11_input", struct( ...
            "sprung_mass_kg", 300.0, ...
            "suspension_stiffness_n_per_m", 16000.0, ...
            "suspension_damping_n_s_per_m", 1000.0, ...
            "road_peak_m", 0.05, ...
            "road_angular_frequency_rad_per_s", 8*pi));
    case "XBATT-02"
        localRequireNames(publicNames, ["ambient_temperature"; ...
            "coolant_inlet_temperature"; "initial_soc"; ...
            "current_demand"; "module_resistance_spread"; ...
            "coolant_maldistribution"; "load_step_time"; ...
            "regen_start_time"]);
        values = struct( ...
            "ambient_temperature", 300.0, ...
            "coolant_inlet_temperature", 298.0, ...
            "initial_soc", 0.82, ...
            "current_demand", 110.0, ...
            "module_resistance_spread", 0.10, ...
            "coolant_maldistribution", 0.22, ...
            "load_step_time", 75.0, ...
            "regen_start_time", 225.0);
    case "XBATT-03"
        localRequireNames(publicNames, ["speed_command"; ...
            "ambient_temperature_C"; "initial_temperature_C"; ...
            "relative_humidity"; "solar_load_W"; ...
            "cabin_temperature_setpoint_C"; "initial_soc"; ...
            "vehicle_mass_kg"; "cooling_enable"]);
        time = (0:1:765).';
        knotsTime = [0; 20; 55; 95; 145; 205; 275; ...
            350; 435; 525; 620; 700; 765];
        knotsSpeed = [0; 32; 0; 48; 18; 58; 0; ...
            42; 12; 64; 20; 46; 0];
        speed = min(max(interp1(knotsTime, knotsSpeed, time, "linear"), ...
            0.0), 130.0);
        values = struct( ...
            "speed_command", timeseries(speed, time), ...
            "ambient_temperature_C", 25.0, ...
            "initial_temperature_C", 25.0, ...
            "relative_humidity", 0.50, ...
            "solar_load_W", 450.0, ...
            "cabin_temperature_setpoint_C", 22.0, ...
            "initial_soc", 0.85, ...
            "vehicle_mass_kg", 1611.0, ...
            "cooling_enable", 1.0);
    case "XBATT-04"
        localRequireNames(publicNames, ["Vmax"; "Vmin"; "Ic"; "Id"; ...
            "ambient_temperature_K"; "initial_temperature_K"; ...
            "number_of_cycles"]);
        values = struct( ...
            "Vmax", 4.2, ...
            "Vmin", 2.5, ...
            "Ic", 1.6666666667, ...
            "Id", -5.0, ...
            "ambient_temperature_K", 298.0, ...
            "initial_temperature_K", 298.0, ...
            "number_of_cycles", 50.0);
    otherwise
        error("SimuVerity:CandidateClosure:First20PublicNominalTaskUnsupported", ...
            "No evaluator-owned first task group nominal provider is registered for %s.", ...
            benchmarkTaskId);
end
end

function localRequireNames(actual, expected)
actual = sort(string(actual(:)));
expected = sort(string(expected(:)));
assert(isequal(actual, expected), ...
    "SimuVerity:CandidateClosure:First20PublicNominalInputContract", ...
    "Evaluator-owned nominal input names do not match the public contract.");
end
