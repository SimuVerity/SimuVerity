function f90_xmech10_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xmech10_reference_clean_replay_setup Run the official project StartUp.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XMECH-10", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMECH-10.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The youBot project may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XMECH-10 requires its exact five-scenario contract.");

originalFolder = string(pwd);
sessionCleanup = onCleanup(@() localRestoreFolder(originalFolder)); %#ok<NASGU>
runtimeRoot = string(pwd);
candidateRoots = [runtimeRoot; fullfile(runtimeRoot, "src")];
expectedProjectBinding = "present";
matches = false(numel(candidateRoots), 1);
for index = 1:numel(candidateRoots)
    candidateProject = fullfile(candidateRoots(index), "YouBot_Arm.prj");
    matches(index) = isfile(candidateProject) && ...
        localFileIdentity(candidateProject) == expectedProjectBinding;
end
assert(nnz(matches) == 1, ...
    "SimuVerity:ReferenceSetup:ProjectClosureMismatch", ...
    "The exact bundled youBot project was not found uniquely.");
projectRoot = candidateRoots(matches);
projectFile = fullfile(projectRoot, "YouBot_Arm.prj");
modelPath = fullfile(projectRoot, "youBot_Arm.slx");
modelName = "youBot_Arm";
expectedModelBinding = ...
    "present";
startupPath = fullfile(projectRoot, "Scripts_Data", "startup_youBot.m");
parameterPath = fullfile(projectRoot, "Scripts_Data", "youBot_PARAM.m");
busPath = fullfile(projectRoot, "Scripts_Data", "Belts_BusObject.mat");
demoPath = fullfile(projectRoot, "Scripts_Data", ...
    "youBot_Arm_Demo_Script.html");
mathLibraryPath = fullfile(projectRoot, "Libraries", "MyMath_lib.slx");
startupDeclaration = fullfile(projectRoot, "resources", "project", ...
    "Root.type.EntryPoints", ...
    "27abb5b8-d24f-4deb-98b9-921908bb282b.type.EntryPoint.xml");
rootPathDeclaration = fullfile(projectRoot, "resources", "project", ...
    "Root.type.ProjectPath", ...
    "39cd7916-cc05-4658-a959-751f5c72b00f.type.Reference.xml");
scriptsPathDeclaration = fullfile(projectRoot, "resources", "project", ...
    "Root.type.ProjectPath", ...
    "d582d1fc-fe89-468a-8c04-33c4fcf64880.type.Reference.xml");
librariesPathDeclaration = fullfile(projectRoot, "resources", "project", ...
    "Root.type.ProjectPath", ...
    "6e09777b-dba0-4043-b91c-a1bba659c4ef.type.Reference.xml");
overviewPathDeclaration = fullfile(projectRoot, "resources", "project", ...
    "Root.type.ProjectPath", ...
    "2f38785a-6b5e-40ce-b211-6e0d026b9bf7.type.Reference.xml");

% Bind the project identity, its Type="StartUp" declaration, the project
% paths needed by that StartUp, and every file it directly consumes.  The
% retained inventory binds the remainder of the model dependency closure.
localAssertAsset(projectFile, ...
    expectedProjectBinding);
localAssertAsset(startupDeclaration, ...
    "present");
declaration = string(fileread(startupDeclaration));
assert(contains(declaration, 'File="Scripts_Data/startup_youBot.m"') && ...
    contains(declaration, 'Type="StartUp"'), ...
    "SimuVerity:ReferenceSetup:ProjectStartupMismatch", ...
    "The exact project StartUp declaration is missing or changed.");
localAssertAsset(rootPathDeclaration, ...
    "present");
localAssertAsset(scriptsPathDeclaration, ...
    "present");
localAssertAsset(librariesPathDeclaration, ...
    "present");
localAssertAsset(overviewPathDeclaration, ...
    "present");
localAssertAsset(startupPath, ...
    "present");
localAssertAsset(parameterPath, ...
    "present");
localAssertAsset(busPath, ...
    "present");
localAssertAsset(demoPath, ...
    "present");
localAssertAsset(mathLibraryPath, ...
    "present");
localAssertAsset(modelPath, expectedModelBinding);

% Opening this exact project executes startup_youBot.m in the same
% before-load phase as the source project.  It invokes youBot_PARAM itself;
% no evaluator-owned workspace value is reconstructed here.
try
    project = openProject(projectRoot); %#ok<NASGU>
    assert(bdIsLoaded(modelName), ...
        "SimuVerity:ReferenceSetup:OfficialModelNotLoaded", ...
        "Official project StartUp did not load the youBot arm model.");
    loadedModelPath = string(get_param(modelName, "FileName"));
    assert(strlength(loadedModelPath) > 0 && isfile(loadedModelPath) && ...
        localSamePath(loadedModelPath, modelPath), ...
        "SimuVerity:ReferenceSetup:OfficialModelPathMismatch", ...
        "Official project StartUp loaded a youBot arm model outside the bound project root.");
    assert(localFileIdentity(loadedModelPath) == expectedModelBinding && ...
        string(get_param(modelName, "Dirty")) == "off", ...
        "SimuVerity:ReferenceSetup:OfficialModelIdentityMismatch", ...
        "Official project StartUp loaded a changed or dirty youBot arm model.");
    assert(evalin("base", "exist('YBT_Par','var') == 1") && ...
        isstruct(evalin("base", "YBT_Par")), ...
        "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
        "Official project StartUp did not define the youBot parameters.");
    assert(evalin("base", "exist('Belt','var') == 1") && ...
        isa(evalin("base", "Belt"), "Simulink.Bus") && ...
        evalin("base", "exist('Belts','var') == 1") && ...
        isa(evalin("base", "Belts"), "Simulink.Bus") && ...
        evalin("base", "exist('t','var') == 1") && ...
        isnumeric(evalin("base", "t")) && ...
        evalin("base", "exist('Qt','var') == 1") && ...
        isnumeric(evalin("base", "Qt")), ...
        "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
        "Official project StartUp did not complete its parameter and bus initialization.");

    % StartUp opens the source model.  The generic clean-replay boundary must
    % load the separately sealed top-level alias, so close only the verified
    % source model and explicitly discard no changes.  Keep the project open:
    % its path and initialized base workspace are required by the next phase.
    localAssertAsset(modelPath, expectedModelBinding);
    close_system(modelName, 0);
    assert(~bdIsLoaded(modelName), ...
        "SimuVerity:ReferenceSetup:OfficialModelCloseFailed", ...
        "The verified project model remained loaded after no-save close.");
    localAssertAsset(modelPath, expectedModelBinding);
catch setupException
    try
        localCloseCurrentProject();
    catch cleanupException
        setupException = addCause(cleanupException, setupException);
    end
    rethrow(setupException);
end
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled youBot initialization asset is missing or changed: %s", ...
    pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
function localRestoreFolder(originalFolder)
cd(originalFolder);
end

function localCloseCurrentProject()
try
    project = currentProject;
    if ~isempty(project)
        close(project);
    end
catch cleanupException
    if strcmp(cleanupException.identifier, ...
            "MATLAB:project:api:NoProjectCurrentlyLoaded")
        return
    end
    rethrow(cleanupException);
end
end
