function f90_xmech02_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xmech02_reference_clean_replay_setup Run the official project StartUp.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XMECH-02", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMECH-02.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The wind-turbine project may only initialize the sealed reference.");
localAssertAsset(officialScenariosPath, ...
    "present");
document = jsondecode(fileread(officialScenariosPath));
expectedScenarioIds = [ ...
    "nominal_start", ...
    "high_wind_regulation", ...
    "positive_direction_change", ...
    "negative_direction_change", ...
    "joint_wind_event"];
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5 && ...
    isequal(string({document.scenarios.id}), expectedScenarioIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XMECH-02 requires its exact five-scenario contract.");

runtimeRoot = string(pwd);
projectRoot = fullfile(runtimeRoot, "Simscape-Wind-Turbine");
candidateAlias = fullfile(runtimeRoot, "Wind_Turbine.slx");
projectPath = fullfile(projectRoot, "Wind_Turbine.prj");
modelPath = fullfile(projectRoot, "Wind_Turbine.slx");
startupDeclaration = fullfile(projectRoot, "resources", "project", ...
    "KAXfQgCar2Yb8zOxgvf9hdmLP1E", ...
    "gCk9bWvODj4OltHaOpaP2lVs9EId.xml");
expectedModelBinding = ...
    "present";
localAssertAsset(candidateAlias, expectedModelBinding);
localAssertAsset(modelPath, expectedModelBinding);
localAssertAsset(projectPath, ...
    "present");
localAssertAsset(startupDeclaration, ...
    "present");
declaration = string(fileread(startupDeclaration));
assert(contains(declaration, 'File="Scripts_Data/startup_Wind_Turbine.m"') && ...
    contains(declaration, 'Type="StartUp"'), ...
    "SimuVerity:ReferenceSetup:ProjectStartupMismatch", ...
    "The exact wind-turbine project StartUp declaration is missing.");

relativeAssets = [ ...
    "LICENSE.md"; ...
    "Scripts_Data/startup_Wind_Turbine.m"; ...
    "Scripts_Data/Setup_WT_Configurations.m"; ...
    "Scripts_Data/Select_Turbine_Systems.m"; ...
    "Scripts_Data/Wind_Turbine_Parameters.m"; ...
    "Scripts_Data/Actuator_Lookup_data.mat"; ...
    "Libraries/Environment/+AerodynamicLoads/BendingSpinningMoments.ssc"];
expectedAssetShas = [ ...
    "present"; ...
    "present"; ...
    "present"; ...
    "present"; ...
    "present"; ...
    "present"; ...
    "present"];
for index = 1:numel(relativeAssets)
    relativePath = replace(relativeAssets(index), "/", filesep);
    localAssertAsset(fullfile(projectRoot, relativePath), ...
        expectedAssetShas(index));
end

originalFolder = string(pwd);
folderCleanup = onCleanup(@() cd(originalFolder)); %#ok<NASGU>
try
    project = openProject(projectPath);
    assert(localSamePath(string(project.RootFolder), projectRoot), ...
        "SimuVerity:ReferenceSetup:ProjectRootMismatch", ...
        "Official project root differs from the bound runtime closure.");
    assert(bdIsLoaded("Wind_Turbine"), ...
        "SimuVerity:ReferenceSetup:OfficialModelNotLoaded", ...
        "Official project StartUp did not load Wind_Turbine.");
    loadedModelPath = string(get_param("Wind_Turbine", "FileName"));
    assert(localSamePath(loadedModelPath, modelPath) && ...
        localFileIdentity(loadedModelPath) == expectedModelBinding, ...
        "SimuVerity:ReferenceSetup:OfficialModelIdentityMismatch", ...
        "Official project StartUp loaded a changed or unbound model.");
    % The project StartUp opens the native model under its basename.  The
    % sealed runtime also supplies a root-level basename alias for evaluation;
    % unload the verified native instance before that alias is loaded.
    close_system("Wind_Turbine", 0);
    assert(evalin("base", "exist('WT_Configs','var') == 1") && ...
        double(evalin("base", ...
            "find(strcmp({WT_Configs.Type}, 'H_Pitch S_Yaw Ge Gn Segments'), 1)")) == 29, ...
        "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
        "Official project StartUp did not create the repository-bundled configuration.");
    localAssertAsset(modelPath, expectedModelBinding);
catch setupException
    try
        localCloseCurrentProject("Wind_Turbine");
    catch cleanupException
        setupException = addCause(setupException, cleanupException);
    end
    rethrow(setupException);
end
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled wind-turbine asset is missing or changed: %s", ...
    pathValue);
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
function localCloseCurrentProject(modelName)
if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
try
    project = currentProject;
    if ~isempty(project)
        close(project);
    end
catch cleanupException
    if strcmp(cleanupException.identifier, ...
            "MATLAB:project:api:NoProjectCurrentlyLoaded")
        return
    end
    rethrow(cleanupException);
end
end
