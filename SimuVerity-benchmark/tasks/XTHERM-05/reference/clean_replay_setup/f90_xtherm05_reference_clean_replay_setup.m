function f90_xtherm05_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xtherm05_reference_clean_replay_setup Open the bundled project.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XTHERM-05", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XTHERM-05.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The battery cooling project may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 9, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XTHERM-05 requires its exact nine-scenario contract.");

publicNames = ["coolant_flow_lpm", "coolant_inlet_temperature_K", ...
    "charge_current_A", "charge_step_fraction", "charge_step_time_s", ...
    "initial_battery_temperature_K", "max_cell_voltage_V"];
publicValues = cell(numel(publicNames), 1);
for index = 1:numel(publicNames)
    name = publicNames(index);
    assert(evalin("base", "exist('" + name + "','var') == 1"), ...
        "SimuVerity:ReferenceSetup:PublicInputMissing", ...
        "Clean replay did not provide public input %s.", name);
    publicValues{index} = evalin("base", name);
end

currentRoot = string(pwd);
candidateRoots = [currentRoot; string(fileparts(currentRoot)); ...
    fullfile(currentRoot, "Battery-Cooling-Plate-Simscape")];
expectedProjectBinding = ...
    "present";
matches = false(numel(candidateRoots), 1);
for index = 1:numel(candidateRoots)
    candidateProject = fullfile(candidateRoots(index), ...
        "BatteryCoolingPlateSimscape.prj");
    matches(index) = isfile(candidateProject) && ...
        localFileIdentity(candidateProject) == expectedProjectBinding;
end
assert(nnz(matches) == 1, ...
    "SimuVerity:ReferenceSetup:ProjectClosureMismatch", ...
    "The exact bundled Battery Cooling Plate project was not found uniquely.");
projectPath = fullfile(candidateRoots(matches), "BatteryCoolingPlateSimscape.prj");
project = openProject(projectPath); %#ok<NASGU>

% Project startup may install its own example defaults.  Restore the exact
% evaluator-owned public nominal inputs without saving or modifying the model.
for index = 1:numel(publicNames)
    assignin("base", char(publicNames(index)), publicValues{index});
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
