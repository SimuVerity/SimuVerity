function ext_xfluid_wecsim_rm3_reference_clean_replay_setup(taskId, officialScenariosPath)
%EXT_XFLUID_WECSIM_RM3_REFERENCE_CLEAN_REPLAY_SETUP Initialize native WEC-Sim.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "EXT-XFLUID-WECSIM-RM3", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to EXT-XFLUID-WECSIM-RM3.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The WEC-Sim source initializer may only configure the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
localAssertAsset(officialScenariosPath, ...
    "present");

document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["nominal_sea", "low_sea_low_damping", ...
    "high_sea_high_damping", "nominal_sea_high_damping"];
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 4 && ...
    isequal(string({document.scenarios.id}), expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "WEC-RM3 requires its exact four-scenario contract.");
scenario = document.scenarios(1);
simulation = document.simulation;
assert(all(isfield(scenario, ...
        ["id", "wave_height_m", "wave_period_s", "pto_damping_n_s_m"])) && ...
    string(scenario.id) == "nominal_sea" && ...
    double(scenario.wave_height_m) == 2.5 && ...
    double(scenario.wave_period_s) == 8.0 && ...
    double(scenario.pto_damping_n_s_m) == 1200000 && ...
    double(simulation.start_time_s) == 0 && ...
    double(simulation.stop_time_s) == 80 && ...
    double(simulation.ramp_time_s) == 15 && ...
    double(simulation.fixed_step_s) == 0.1, ...
    "SimuVerity:ReferenceSetup:FirstScenarioMismatch", ...
    "WEC-RM3 first official scenario changed.");

% Clean replay runs from its evaluator-owned copy of the complete bundled
% reference. Bind the exact source bootstrap, initializer, input, and model;
% the retained inventory binds the rest of the transitive WEC-Sim closure.
assetRoot = string(pwd);
repoRoot = fullfile(assetRoot, "repo");
caseRoot = fullfile(repoRoot, "examples", "RM3");
addSource = fullfile(repoRoot, "addWecSimSource.m");
initializer = fullfile(repoRoot, "source", "functions", "initializeWecSim.m");
inputFile = fullfile(caseRoot, "wecSimInputFile.m");
modelPath = fullfile(caseRoot, "RM3.slx");
candidateAlias = fullfile(assetRoot, "RM3.slx");
modelName = "RM3";
expectedModelBinding = ...
    "present";
localAssertAsset(addSource, ...
    "present");
localAssertAsset(initializer, ...
    "present");
localAssertAsset(inputFile, ...
    "present");
localAssertAsset(modelPath, expectedModelBinding);
localAssertAsset(candidateAlias, expectedModelBinding);

try
cd(repoRoot);
run(addSource);
resolvedInitializer = string(which("initializeWecSim"));
assert(strlength(resolvedInitializer) > 0 && ...
    localSamePath(resolvedInitializer, initializer), ...
    "SimuVerity:ReferenceSetup:InitializerIdentityMismatch", ...
    "initializeWecSim did not resolve to the repository-bundled bundled source.");

% Match the mature native reference adapter exactly for the first official
% scenario.  WEC-Sim configures hydrodynamic mask parameters in the loaded
% model's memory, so select the repository-local evaluator alias in MCR before its
% native initializer runs rather than loading a second same-name model later.
addpath(assetRoot, '-begin');
mcr = struct;
mcr.header = {'waves.height', 'waves.period', 'pto(1).damping', ...
    'simu.caseDir', 'simu.simMechanicsFile', 'simu.endTime', ...
    'simu.rampTime', 'simu.dt', 'simu.explorer'};
mcr.cases = {double(scenario.wave_height_m), ...
    double(scenario.wave_period_s), double(scenario.pto_damping_n_s_m), ...
    char(assetRoot), 'RM3.slx', double(simulation.stop_time_s), ...
    double(simulation.ramp_time_s), ...
    double(simulation.fixed_step_s), "off"};
assignin("base", "mcr", mcr);
assignin("base", "imcr", 1);
cd(caseRoot);
evalin("base", "initializeWecSim");
localRestoreFileGeneration();

assert(bdIsLoaded(modelName), ...
    "SimuVerity:ReferenceSetup:OfficialModelNotLoaded", ...
    "Native WEC-Sim initialization did not load RM3.");
loadedModelPath = string(get_param(modelName, "FileName"));
assert(isfile(loadedModelPath) && ...
    localSamePath(loadedModelPath, candidateAlias) && ...
    localFileIdentity(loadedModelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:OfficialModelIdentityMismatch", ...
    "Native initialization loaded a changed or unbound RM3 model.");

required = ["mcr", "imcr", "simu", "waves", "body", "pto", "constraint"];
for index = 1:numel(required)
    assert(evalin("base", "exist('" + required(index) + "','var') == 1"), ...
        "SimuVerity:ReferenceSetup:NativeWorkspaceIncomplete", ...
        "Native WEC-Sim initialization did not create %s.", required(index));
end
mcrActual = evalin("base", "mcr");
imcrActual = evalin("base", "imcr");
simu = evalin("base", "simu");
waves = evalin("base", "waves");
body = evalin("base", "body");
pto = evalin("base", "pto");
constraint = evalin("base", "constraint");
assert(isequal(string(mcrActual.header), string(mcr.header)) && ...
    isequal(mcrActual.cases, mcr.cases) && imcrActual == 1 && ...
    isa(simu, 'simulationClass') && isa(waves, 'waveClass') && ...
    isa(body, 'bodyClass') && isa(pto, 'ptoClass') && ...
    isa(constraint, 'constraintClass'), ...
    "SimuVerity:ReferenceSetup:NativeWorkspaceIncomplete", ...
    "Native WEC-Sim workspace types or MCR identity are incomplete.");
assert(localSamePath(string(simu.simMechanicsFile), candidateAlias) && ...
    simu.endTime == 80 && simu.rampTime == 15 && ...
    simu.dt == 0.1 && string(simu.explorer) == "off" && ...
    waves.height == double(scenario.wave_height_m) && ...
    waves.period == double(scenario.wave_period_s) && ...
    pto(1).damping == 1200000 && ...
    pto(1).damping == double(scenario.pto_damping_n_s_m), ...
    "SimuVerity:ReferenceSetup:NativeWorkspacePostcondition", ...
    "Native WEC-Sim workspace differs from the first official scenario.");
cd(assetRoot);
localAssertAsset(modelPath, expectedModelBinding);
localAssertAsset(candidateAlias, expectedModelBinding);
catch setupException
    try
        if bdIsLoaded(modelName), close_system(modelName, 0); end
    catch cleanupException
        setupException = addCause(setupException, cleanupException);
    end
    try, cd(assetRoot); catch, end
    rethrow(setupException);
end

% The initialized alias stays loaded for the generic clean-replay helper.
end

function localRestoreFileGeneration()
cache = string(getenv("SIMULINK_CACHE_FOLDER"));
codegen = string(getenv("SIMULINK_CODEGEN_FOLDER"));
assert(strlength(cache) > 0 && strlength(codegen) > 0, ...
    "SimuVerity:ReferenceSetup:Isolation", ...
    "Isolated Simulink cache/codegen paths are missing.");
if ~isfolder(cache), mkdir(cache); end
if ~isfolder(codegen), mkdir(codegen); end
Simulink.fileGenControl("set", "CacheFolder", cache, ...
    "CodeGenFolder", codegen, "createDir", true);
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled WEC-Sim asset is missing or changed: %s", pathValue);
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
