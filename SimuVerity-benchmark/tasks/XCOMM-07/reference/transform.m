function report = transform(sourceDir, destinationDir)
%F90_XCOMM_07_TRANSFORM Public, non-destructive importer transform hook.
arguments
    sourceDir (1,1) string
    destinationDir (1,1) string
end
assert(isfolder(sourceDir), "SimuVerity:Importer:MissingSource", ...
    "R2025a source directory was not found: %s", sourceDir);
assert(~strcmpi(char(sourceDir), char(destinationDir)), ...
    "SimuVerity:Importer:InPlaceForbidden", ...
    "Importer must write to a separate cache directory.");
if ~isfolder(destinationDir), mkdir(destinationDir); end
sourceHelper = fullfile(sourceDir, "helperwlanGenerateWaveform.m");
assert(isfile(sourceHelper), ...
    "SimuVerity:Importer:CompatibilitySourceMissing", ...
    "The official R2025a waveform helper is missing.");
copyfile(fullfile(sourceDir, "*"), destinationDir);
% R2025a ships this example helper with three calls to an internal API that
% is not present in the installed product.  Remove only those inert warning
% suppression calls from the evaluator-owned imported copy.  Waveform,
% channel, CFO and noise calculations remain byte-for-byte otherwise.
helperPath = fullfile(destinationDir, "helperwlanGenerateWaveform.m");
assert(isfile(helperPath), "SimuVerity:Importer:CompatibilitySourceMissing", ...
    "The source-bound waveform helper is missing after import.");
source = string(fileread(helperPath));
statements = [ ...
    "Simulink.suppressDiagnostic(gcb,'SimulinkFixedPoint:util:Overflowoccurred');"; ...
    "Simulink.suppressDiagnostic(gcb,'SimulinkFixedPoint:util:fxpParameterPrecisionLoss');"; ...
    "Simulink.suppressDiagnostic(gcb,'SimulinkFixedPoint:util:fxpParameterOverflow');"];
for index = 1:numel(statements)
    assert(count(source, statements(index)) == 1, ...
        "SimuVerity:Importer:CompatibilitySourceMismatch", ...
        "Expected exactly one unavailable diagnostic API call in the official helper.");
    source = replace(source, statements(index), ...
        "% SimuVerity: unavailable internal diagnostic suppression omitted.");
end
localWriteText(helperPath, source);
report = struct("task_id", "F90-XCOMM-07", "status", ...
    "COMPATIBILITY_COPY_COMPLETE", ...
    "core_source_modifications", 0, ...
    "compatibility_source_modifications", numel(statements));
end

function localWriteText(pathValue, textValue)
fid = fopen(pathValue, "w", "n", "UTF-8");
assert(fid >= 0, "SimuVerity:Importer:CompatibilityWriteFailed", ...
    "Cannot write the evaluator-owned compatibility copy.");
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fwrite(fid, unicode2native(char(textValue), "UTF-8"), "uint8");
end
