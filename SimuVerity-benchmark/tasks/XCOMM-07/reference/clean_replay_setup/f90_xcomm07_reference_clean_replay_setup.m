function f90_xcomm07_reference_clean_replay_setup(taskId, officialScenariosPath)
%F90_XCOMM07_REFERENCE_CLEAN_REPLAY_SETUP Initialize the exact reference before load.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XCOMM-07", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XCOMM-07.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);

assetRoot = string(pwd);
requiredFiles = ["createBus.m"; "helperwlanGenerateWaveform.m"; ...
    "wlanhdlRxParameters.m"];
assert(all(arrayfun(@(name) isfile(fullfile(assetRoot, name)), requiredFiles)), ...
    "SimuVerity:ReferenceSetup:AssetClosureMissing", ...
    "The imported XCOMM-07 reference initialization closure is incomplete.");
addpath(assetRoot, "-begin");

document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "scenarios") && ~isempty(document.scenarios), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XCOMM-07 requires at least one official scenario.");
definition = document.scenarios(1);
assignin("base", "chanBW", "CBW20");
assignin("base", "frameFormat", "VHT");
assignin("base", "MCS", definition.mcs);
assignin("base", "chanCoding", definition.channel_coding);
assignin("base", "numPkts", 1);
assignin("base", "snr", definition.snr_dB);
assignin("base", "CFO", definition.carrier_frequency_offset_Hz);
evalin("base", "[rxWaveform,wlanConfig,cfg,ind,indSigA,chanBWIndex]=" + ...
    "helperwlanGenerateWaveform(chanBW,frameFormat,MCS,chanCoding,snr,CFO,numPkts);");
evalin("base", "validIn=true(length(rxWaveform),1); " + ...
    "startIn=[true;false(length(rxWaveform)-1,1)];");
evalin("base", "stopTime=(length(rxWaveform)+2500)/wlanConfig.Fs; " + ...
    "filterUpsampleFactor=160e6/wlanConfig.Fs; " + ...
    "filterLatency=(wlanConfig.corrLen/filterUpsampleFactor)+filterUpsampleFactor+9;");
parameterScript = replace(fullfile(assetRoot, "wlanhdlRxParameters.m"), "\", "/");
evalin("base", "run('" + replace(parameterScript, "'", "''") + "')");
evalin("base", "hconstellationBus=createBus(" + ...
    "{'headerConstellationPoints','complex',1,'fixdt(1,16,14)'}," + ...
    "{'headerConstellationValid','real',1,'boolean'});");
evalin("base", "dconstellationBus=createBus(" + ...
    "{'dataConstellationPoints','complex',1,'fixdt(1,16,14)'}," + ...
    "{'dataConstellationValid','real',1,'boolean'});");
evalin("base", "diagBus=createBus(" + ...
    "{'decodedMCS','real',1,'fixdt(0,3,0)'}," + ...
    "{'PSDULen','real',1,'uint16'}," + ...
    "{'signalParityStatus','real',1,'boolean'}," + ...
    "{'signalCRCStatus','real',1,'boolean'}," + ...
    "{'frameFormat','real',1,'fixdt(0,2,0)'}," + ...
    "{'headerConstellation','real',1,'Bus: hconstellationBus'}," + ...
    "{'dataConstellation','real',1,'Bus: dconstellationBus'}," + ...
    "{'packetDetected','real',1,'boolean'}," + ...
    "{'freqOffset','real',1,'fixdt(1,14,14)'});");
end
