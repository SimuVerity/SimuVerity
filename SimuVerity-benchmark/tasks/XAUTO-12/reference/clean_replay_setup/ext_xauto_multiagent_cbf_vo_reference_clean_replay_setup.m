function ext_xauto_multiagent_cbf_vo_reference_clean_replay_setup(taskId, officialScenariosPath)
%EXT_XAUTO_MULTIAGENT_CBF_VO_REFERENCE_CLEAN_REPLAY_SETUP
% Initialize the exact bundled reference workspace before model loading.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "EXT-XAUTO-MULTIAGENT-CBF-VO", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to EXT-XAUTO-MULTIAGENT-CBF-VO.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The native CBF-VO workspace may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);

sourceRoot = fullfile(string(pwd), "source", "car_dynamics");
assert(isfolder(sourceRoot) && ...
    isfile(fullfile(sourceRoot, "setup_functions", "actorInitialization.m")), ...
    "SimuVerity:ReferenceSetup:AssetClosureMissing", ...
    "The bundled CBF-VO source runtime is incomplete.");
% Native mask callbacks use source-root-relative script paths.  This MATLAB
% process owns its current directory, so retain the evaluator-owned source
% root through load/update/compile/sim without touching the sealed bundle.
cd(sourceRoot);

document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "task_id") && ...
    string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 4, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The CBF-VO reference requires its exact four-scenario contract.");
scenario = document.scenarios(1);
localAssertScenario(scenario);

config = struct("t_max", scenario.duration_s, "timestep", 0.05, ...
    "geometric_tol", 0.1, "R_circle", 20, ...
    "R_agent", scenario.agent_radius_m, "p0_std", 0, ...
    "v_mod", scenario.preferred_speed_mps, "v_max", 10, ...
    "u_max", scenario.maximum_acceleration_mps2, ...
    "tan_phi_max", scenario.maximum_steering_tangent, ...
    "alpha_vo", 100, "alpha_c", 10, "k_u", 1, "k_vo", 1, ...
    "P", [1/5;1/2], "D", [0;0.1], "goal_reached_tol", 1, ...
    "consider_only_min_t_col", false, ...
    "include_VO_as_hard_constraint", false, ...
    "max_iterations_fail", 3, "use_safe_cbf", true);

global agentsInfo
agentsInfo = cell(1, 8);
for agent = 1:8
    agentsInfo{agent} = struct( ...
        "p", [scenario.initial_positions_m(agent,:) 0].', ...
        "v", scenario.initial_speeds_mps(agent), ...
        "theta", scenario.initial_headings_rad(agent), ...
        "p_goal", [scenario.goal_positions_m(agent,:) 0].', ...
        "dim", [scenario.agent_radius_m;scenario.agent_radius_m], ...
        "debug", true, ...
        "passive", logical(scenario.passive_agents(agent)));
end

mission = rmfield(scenario, "id");
assignin("base", "multiagent_mission", mission);
assignin("base", "config", config);
assignin("base", "n_agents", 8);
assignin("base", "cameraTranslation", [0 0 50]);
assignin("base", "cameraRotation", [0 90 90]);
assignin("base", "agentsInfo", agentsInfo);
assignin("base", "Ts", config.timestep);
end

function localAssertScenario(scenario)
required = ["id", "duration_s", "initial_positions_m", ...
    "goal_positions_m", "initial_speeds_mps", ...
    "initial_headings_rad", "agent_radius_m", ...
    "preferred_speed_mps", "maximum_acceleration_mps2", ...
    "maximum_steering_tangent", "passive_agents"];
assert(all(isfield(scenario, required)), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The nominal CBF-VO scenario is incomplete.");
assert(isequal(size(scenario.initial_positions_m), [8 2]) && ...
    isequal(size(scenario.goal_positions_m), [8 2]) && ...
    numel(scenario.initial_speeds_mps) == 8 && ...
    numel(scenario.initial_headings_rad) == 8 && ...
    numel(scenario.passive_agents) == 8, ...
    "SimuVerity:ReferenceSetup:ScenarioShape", ...
    "The nominal CBF-VO scenario has an invalid eight-agent shape.");
end
