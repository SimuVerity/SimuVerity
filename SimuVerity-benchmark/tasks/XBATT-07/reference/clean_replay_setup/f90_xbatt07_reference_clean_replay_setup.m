function f90_xbatt07_reference_clean_replay_setup( ...
        taskId, officialScenariosPath)
%F90_XBATT07_REFERENCE_CLEAN_REPLAY_SETUP Load the exact native project.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end

assert(taskId == "F90-XBATT-07", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XBATT-07.");
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The exact current XBATT-07 official scenarios are required.");
document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["nominal_standby", "drive_precharge_ready", ...
    "drive_precharge_incomplete", "charge_precharge_ready", ...
    "voltage_temperature_derating", ...
    "overvoltage_overtemperature_fault"];
assert(string(document.task_id) == "F90-XBATT-07" && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 6 && ...
    isequal(string({document.scenarios.id}), expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The XBATT-07 scenario identity or ordering differs.");

submissionRoot = string(pwd);
archivePath = fullfile(submissionRoot, "BatteryManagementSystem.mlproj");
modelPath = fullfile(submissionRoot, "XBATT07_reference_harness.slx");
licensePath = fullfile(submissionRoot, "license.txt");
expectedArchiveBinding = ...
    "present";
expectedModelBinding = ...
    "present";
expectedLicenseBinding = ...
    "present";
assert(isfile(archivePath) && localFileIdentity(archivePath) == expectedArchiveBinding && ...
    isfile(modelPath) && localFileIdentity(modelPath) == expectedModelBinding && ...
    isfile(licensePath) && localFileIdentity(licensePath) == expectedLicenseBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceClosure", ...
    "The evaluator-owned XBATT-07 project closure is incomplete or changed.");

projectRoot = fullfile(submissionRoot, ".simuverity_xbatt07_project");
assert(~isfolder(projectRoot) && ~isfile(projectRoot), ...
    "SimuVerity:ReferenceSetup:RuntimeReuse", ...
    "The clean-replay project directory already exists.");
project = [];
try
    matlab.project.extractProject(archivePath, projectRoot);
    project = matlab.project.loadProject(projectRoot);
    assert(~isempty(project), ...
        "SimuVerity:ReferenceSetup:ProjectLoad", ...
        "The exact XBATT-07 MATLAB project did not load.");
    assert(localFileIdentity(archivePath) == expectedArchiveBinding && ...
        localFileIdentity(modelPath) == expectedModelBinding && ...
        localFileIdentity(licensePath) == expectedLicenseBinding, ...
        "SimuVerity:ReferenceSetup:ReferenceModified", ...
        "Loading the native project changed a sealed reference asset.");
catch setupException
    try
        if ~isempty(project), close(project); end
    catch
    end
    rethrow(setupException)
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
