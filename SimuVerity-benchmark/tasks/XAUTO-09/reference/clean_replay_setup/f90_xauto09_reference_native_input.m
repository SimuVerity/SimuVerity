function f90_xauto09_reference_native_input(model, assetRoot)
%F90_XAUTO09_REFERENCE_NATIVE_INPUT Capture official harness inputs.
% The exact controller model is left unchanged on disk. The official test
% bench is simulated once to capture the six native signals at its model
% reference boundary, then those signals are supplied to the standalone
% reference model for the evaluator-owned clean replay only.
arguments
    model (1,1) string
    assetRoot (1,1) string
end
assert(bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelNotLoaded", ...
    "Standalone reference model is not loaded.");
harness = "LaneFollowingTestBenchExample";
harnessPath = fullfile(assetRoot, harness + ".slx");
assert(isfile(harnessPath), ...
    "SimuVerity:ReferenceSetup:NativeHarnessMissing", ...
    "Official XAUTO-09 native harness is missing.");
load_system(harnessPath);

referenceBlocks = find_system(harness, ...
    "FollowLinks", "on", "LookUnderMasks", "all", ...
    "BlockType", "ModelReference");
referenceNames = string(get_param(referenceBlocks, "ModelName"));
referenceBlock = referenceBlocks(referenceNames == "LFRefMdl");
assert(numel(referenceBlock) == 1, ...
    "SimuVerity:ReferenceSetup:NativeHarnessBoundary", ...
    "Official XAUTO-09 harness must contain one LFRefMdl boundary.");
portHandles = get_param(referenceBlock{1}, "PortHandles");
inputPorts = portHandles.Inport(:);
assert(numel(inputPorts) == 6, ...
    "SimuVerity:ReferenceSetup:NativeHarnessBoundary", ...
    "Official XAUTO-09 harness must drive all six controller inputs.");
inputLines = arrayfun(@(port) get_param(port, "Line"), inputPorts);
assert(all(inputLines ~= -1), ...
    "SimuVerity:ReferenceSetup:NativeHarnessBoundary", ...
    "Official XAUTO-09 harness has a disconnected controller input.");
loggingPorts = arrayfun(@(line) get_param(line, "SrcPortHandle"), inputLines);
assert(all(loggingPorts > 0), ...
    "SimuVerity:ReferenceSetup:NativeHarnessBoundary", ...
    "Official XAUTO-09 harness has an input without an exact source port.");

loggingNames = "F90_XAUTO09_NATIVE_INPUT_" + string(1:numel(inputLines));
oldLogging = strings(size(loggingPorts));
oldNameMode = strings(size(loggingPorts));
oldLogName = strings(size(loggingPorts));
for index = 1:numel(loggingPorts)
    oldLogging(index) = string(get_param(loggingPorts(index), "DataLogging"));
    oldNameMode(index) = string(get_param(loggingPorts(index), ...
        "DataLoggingNameMode"));
    oldLogName(index) = string(get_param(loggingPorts(index), "DataLoggingName"));
    set_param(loggingPorts(index), ...
        "DataLogging", "on", ...
        "DataLoggingNameMode", "Custom", ...
        "DataLoggingName", loggingNames(index));
end
lineCleanup = onCleanup(@() localRestoreLoggingPorts(loggingPorts, ...
    oldLogging, oldNameMode, oldLogName)); %#ok<NASGU>

config = getActiveConfigSet(harness);
if isa(config, "Simulink.ConfigSetRef"), config = getRefConfigSet(config); end
oldConfig = struct( ...
    "ReturnWorkspaceOutputs", string(get_param(config, "ReturnWorkspaceOutputs")), ...
    "SignalLogging", string(get_param(config, "SignalLogging")), ...
    "LimitDataPoints", string(get_param(config, "LimitDataPoints")), ...
    "StopTime", string(get_param(config, "StopTime")));
configCleanup = onCleanup(@() localRestoreConfig(config, oldConfig)); %#ok<NASGU>
captureStopTime = double(evalin("base", "simStopTime"));
assert(isfinite(captureStopTime) && captureStopTime > 0, ...
    "SimuVerity:ReferenceSetup:NativeCaptureHorizon", ...
    "Official XAUTO-09 native capture horizon must be finite and positive.");
set_param(config, ...
    "ReturnWorkspaceOutputs", "on", ...
    "SignalLogging", "on", ...
    "LimitDataPoints", "off", ...
    "StopTime", num2str(captureStopTime, 17));
set_param(harness, "SimulationMode", "normal");
nativeOutput = sim(harness, "ReturnWorkspaceOutputs", "on");
nativeLogs = nativeOutput.logsout;
assert(isa(nativeLogs, "Simulink.SimulationData.Dataset"), ...
    "SimuVerity:ReferenceSetup:NativeHarnessEvidence", ...
    "Official XAUTO-09 harness did not return native input logs.");

portNames = ["Vision", "Radar", "Driver Set Velocity", ...
    "Longitudinal Velocity", "Lane Sensor", "System Clock"];
localDisableBusRootInterpolation(model);
nativeInput = Simulink.SimulationData.Dataset;
for index = 1:numel(portNames)
    signal = nativeLogs.getElement(loggingNames(index));
    assert(~isempty(signal), ...
        "SimuVerity:ReferenceSetup:NativeHarnessEvidence", ...
        "Official XAUTO-09 harness omitted input %s.", portNames(index));
    nativeInput = nativeInput.addElement(signal.Values, portNames(index));
end
inputVariable = "F90_XAUTO09_REFERENCE_NATIVE_INPUT";
assignin("base", inputVariable, nativeInput);
set_param(model, "LoadExternalInput", "on", ...
    "ExternalInput", inputVariable);
% The current standalone reference has StopTime=inf because the official
% harness owns its simulation horizon.  Bound this evaluator-only replay to
% the exact horizon used to capture the six boundary inputs; otherwise the
% model extrapolates past the official data and eventually trips its
% positive-longitudinal-velocity assertion.
set_param(model, "StopTime", num2str(captureStopTime, 17));
assert(str2double(get_param(model, "StopTime")) == captureStopTime, ...
    "SimuVerity:ReferenceSetup:NativeCaptureHorizon", ...
    "Standalone XAUTO-09 replay did not retain the native capture horizon.");
end

function localDisableBusRootInterpolation(model)
expectedRootNames = ["Vision", "Radar", "Driver Set Velocity", ...
    "Longitudinal Velocity", "Lane Sensor", "System Clock"];
rootInports = reshape(string(find_system(model, ...
    "SearchDepth", 1, "BlockType", "Inport")), 1, []);
rootNames = reshape(string(get_param(cellstr(rootInports), "Name")), 1, []);
assert(numel(rootInports) == numel(expectedRootNames) && ...
    isequal(sort(rootNames), sort(expectedRootNames)), ...
    "SimuVerity:ReferenceSetup:NativeRootInportContract", ...
    "The exact XAUTO-09 reference root Inport set changed.");
for index = 1:numel(expectedRootNames)
    root = rootInports(rootNames == expectedRootNames(index));
    assert(numel(root) == 1 && ...
        string(get_param(root, "Port")) == string(index), ...
        "SimuVerity:ReferenceSetup:NativeRootInportContract", ...
        "The exact XAUTO-09 root Inport ordering changed.");
end

busRootNames = ["Vision", "Radar", "Lane Sensor"];
busRootTypes = ["Bus: BusVision", "Bus: BusRadar", "Bus: LaneSensor"];
for index = 1:numel(busRootNames)
    busRoot = rootInports(rootNames == busRootNames(index));
    assert(numel(busRoot) == 1 && ...
        string(get_param(busRoot, "OutDataTypeStr")) == busRootTypes(index), ...
        "SimuVerity:ReferenceSetup:NativeBusInportContract", ...
        "The exact XAUTO-09 bus root Inport type changed.");
    set_param(busRoot, "Interpolate", "off");
    assert(string(get_param(busRoot, "Interpolate")) == "off", ...
        "SimuVerity:ReferenceSetup:NativeBusInterpolation", ...
        "The exact XAUTO-09 bus root Inport still enables interpolation.");
end
end

function localRestoreLoggingPorts(ports, logging, nameMode, logName)
for index = 1:numel(ports)
    try
        set_param(ports(index), ...
            "DataLogging", logging(index), ...
            "DataLoggingNameMode", nameMode(index), ...
            "DataLoggingName", logName(index));
    catch
    end
end
end

function localRestoreConfig(config, value)
try
    set_param(config, ...
        "ReturnWorkspaceOutputs", value.ReturnWorkspaceOutputs, ...
        "SignalLogging", value.SignalLogging, ...
        "LimitDataPoints", value.LimitDataPoints, ...
        "StopTime", value.StopTime);
catch
end
end
