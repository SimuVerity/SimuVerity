function f90_xauto09_reference_clean_replay_setup(taskId, officialScenariosPath, model)
%F90_XAUTO09_REFERENCE_CLEAN_REPLAY_SETUP Bind the native reference input.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end
assert(taskId == "F90-XAUTO-09", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XAUTO-09.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
assert(bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelNotLoaded", ...
    "The exact XAUTO-09 reference model must be loaded before setup.");

expectedReferenceBinding = ...
    "present";
candidatePath = string(get_param(model, "FileName"));
assert(isfile(candidatePath) && ...
    localFileIdentity(candidatePath) == expectedReferenceBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceIdentity", ...
    "The loaded subject is not the exact repository-bundled XAUTO-09 reference.");
assetRoot = string(fileparts(candidatePath));
helper = fullfile(assetRoot, "helperLFSetUp.m");
busSetup = fullfile(assetRoot, "createLaneSensorBuses.m");
harness = fullfile(assetRoot, "LaneFollowingTestBenchExample.slx");
referenceModel = fullfile(assetRoot, "LFRefMdl.slx");
localAssertAsset(helper, ...
    "present");
localAssertAsset(busSetup, ...
    "present");
localAssertAsset(harness, ...
    "present");
localAssertAsset(referenceModel, expectedReferenceBinding);

nativeHelper = fullfile(fileparts(mfilename("fullpath")), ...
    "f90_xauto09_reference_native_input.m");
localAssertAsset(nativeHelper, ...
    "present");
addpath(assetRoot, "-begin");

document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "scenarios") && ~isempty(document.scenarios), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XAUTO-09 requires at least one official scenario.");
scenario = document.scenarios(1);
scenarioName = replace(string(scenario.source_scenario), "'", "''");
evalin("base", "helperLFSetUp('ScenarioFcnName','" + scenarioName + "');");
assignin("base", "v_set", double(scenario.driver_set_velocity_mps));
assignin("base", "time_gap", double(scenario.time_gap_s));
assignin("base", "default_spacing", double(scenario.default_spacing_m));

setupDirectory = string(fileparts(nativeHelper));
addpath(setupDirectory, "-begin");
setupPathCleanup = onCleanup(@() rmpath(setupDirectory)); %#ok<NASGU>
feval("f90_xauto09_reference_native_input", model, assetRoot);
assert(localFileIdentity(candidatePath) == expectedReferenceBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceModified", ...
    "Native input capture changed the sealed XAUTO-09 reference file.");
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled lane-following asset is missing or changed: %s", ...
    pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
