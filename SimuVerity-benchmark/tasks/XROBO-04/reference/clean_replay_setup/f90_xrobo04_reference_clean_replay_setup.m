function f90_xrobo04_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xrobo04_reference_clean_replay_setup Run the official rover StartUp.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XROBO-04", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XROBO-04.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The Mars rover project may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);

document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XROBO-04 requires its exact five-scenario contract.");
scenarioIds = string({document.scenarios.id});
assert(isequal(scenarioIds(:), [ ...
    "nominal_path1_uneven"; ...
    "path2_uneven"; ...
    "path2_flat"; ...
    "path1_low_speed"; ...
    "path1_low_friction"]), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The ordered XROBO-04 scenario authority changed.");
scenario = document.scenarios(1);
assert(string(scenario.id) == "nominal_path1_uneven" && ...
    string(scenario.class) == "nominal" && ...
    double(scenario.path_id) == 1 && ...
    string(scenario.terrain) == "uneven" && ...
    double(scenario.TargetSpeed_mps) == 0.03 && ...
    double(scenario.TerrainMuStatic) == 0.8 && ...
    double(scenario.TerrainMuDynamic) == 0.6, ...
    "SimuVerity:ReferenceSetup:NominalScenarioMismatch", ...
    "The first official XROBO-04 scenario changed.");

assetRoot = string(pwd);
projectFile = fullfile(assetRoot, "Mars_Rover_Terrain.prj");
modelFile = fullfile(assetRoot, "Models", "mars_rover_terrain.slx");
candidateAlias = fullfile(assetRoot, "mars_rover_terrain.slx");
model = "mars_rover_terrain";
startupDeclaration = fullfile(assetRoot, "resources", "project", ...
    "KAXfQgCar2Yb8zOxgvf9hdmLP1E", ...
    "FOxD48oK_Cam4cSPQDoLH8emRIAd.xml");
startupFile = fullfile(assetRoot, "Scripts_Data", ...
    "startup_mars_rover_terrain.m");
parametersRoot = fullfile(assetRoot, "Scripts_Data", "Parameters");
parametersAll = fullfile(parametersRoot, "mars_rover_params_all.m");
parametersChassis = fullfile(parametersRoot, "mars_rover_params_chassis.m");
parametersArm = fullfile(parametersRoot, "mars_rover_params_arm.m");
targetPath = fullfile(parametersRoot, "mars_rover_chassis_target_path.mat");
gridRoot = fullfile(assetRoot, "Workflows", "Grid_Surface");
gridBuilder = fullfile(gridRoot, "stl_to_gridsurface.m");
terrainStl = fullfile(gridRoot, "mars_terrain.stl");
terrainSelector = fullfile(gridRoot, "mars_terrain_set_z.m");
pointCloud = fullfile(assetRoot, "Workflows", "Point_Cloud", ...
    "mars_rover_terrain_ptcloud_wheel.mat");
inverseKinematicsRoot = fullfile(assetRoot, "Workflows", ...
    "Inverse_Kinematics");
armTaskSpace = fullfile(inverseKinematicsRoot, ...
    "mars_rover_arm_task_space.m");
armIkFactory = fullfile(inverseKinematicsRoot, ...
    "mars_rover_arm_ik_object_create.m");
armModel = fullfile(inverseKinematicsRoot, "mars_rover_arm.slx");
overviewFile = fullfile(assetRoot, "Overview", "mars_rover_terrain.m");
expectedModelBinding = ...
    "present";

% Bind the official project identity, its Type="StartUp" declaration and
% every source asset directly consumed by that initialization chain.  The
% retained inventory binds the remainder of the unmodified project closure.
localAssertAsset(projectFile, ...
    "present");
localAssertAsset(startupDeclaration, ...
    "present");
declaration = string(fileread(startupDeclaration));
assert(contains(declaration, ...
        'File="Scripts_Data/startup_mars_rover_terrain.m"') && ...
    contains(declaration, 'Type="StartUp"'), ...
    "SimuVerity:ReferenceSetup:ProjectStartupMismatch", ...
    "The exact Mars rover project StartUp declaration is missing or changed.");
localAssertAsset(startupFile, ...
    "present");
localAssertAsset(parametersAll, ...
    "present");
localAssertAsset(parametersChassis, ...
    "present");
localAssertAsset(parametersArm, ...
    "present");
localAssertAsset(targetPath, ...
    "present");
localAssertAsset(gridBuilder, ...
    "present");
localAssertAsset(terrainStl, ...
    "present");
localAssertAsset(terrainSelector, ...
    "present");
localAssertAsset(pointCloud, ...
    "present");
localAssertAsset(armTaskSpace, ...
    "present");
localAssertAsset(armIkFactory, ...
    "present");
localAssertAsset(armModel, ...
    "present");
localAssertAsset(overviewFile, ...
    "present");
localAssertAsset(modelFile, expectedModelBinding);
localAssertAsset(candidateAlias, expectedModelBinding);

originalFolder = string(pwd);
folderCleanup = onCleanup(@() cd(originalFolder)); %#ok<NASGU>
try
    % openProject executes the exact project-owned StartUp in this process.
    % No evaluator-owned parameter reconstruction substitutes for it.
    project = openProject(projectFile); %#ok<NASGU>
    assert(localSamePath(string(project.RootFolder), assetRoot), ...
        "SimuVerity:ReferenceSetup:ProjectRootMismatch", ...
        "The opened Mars rover project is outside the bundled asset root.");
    localAssertWorkspace;

    % The evaluator also stages an exact-byte root alias for generic replay.
    % Project StartUp may resolve either same-name path.  Accept only those
    % two repository-bundled copies; if it loaded the nested source path, close it
    % without saving and continue on the sealed alias that generic replay
    % will load next.  This preserves StartUp workspace state while avoiding
    % a same-model-name/full-path conflict.
    assert(bdIsLoaded(model), ...
        "SimuVerity:ReferenceSetup:OfficialModelNotLoaded", ...
        "The exact Mars rover model did not load after official StartUp.");
    loadedModelPath = string(get_param(model, "FileName"));
    assert(localSamePath(loadedModelPath, modelFile) || ...
        localSamePath(loadedModelPath, candidateAlias), ...
        "SimuVerity:ReferenceSetup:OfficialModelPathMismatch", ...
        "A Mars rover model outside the bound project closure was loaded.");
    localAssertAsset(loadedModelPath, expectedModelBinding);
    if localSamePath(loadedModelPath, modelFile)
        close_system(model, 0);
        assert(~bdIsLoaded(model), ...
            "SimuVerity:ReferenceSetup:SourceModelCloseFailed", ...
            "The nested source model remained loaded after no-save close.");
        load_system(candidateAlias);
    end
    assert(bdIsLoaded(model) && ...
        localSamePath(string(get_param(model, "FileName")), candidateAlias), ...
        "SimuVerity:ReferenceSetup:RuntimeAliasMismatch", ...
        "The exact sealed Mars rover runtime alias is not loaded.");
    localApplyScenario(model, scenario);
    localAssertAsset(candidateAlias, expectedModelBinding);
    localAssertAsset(modelFile, expectedModelBinding);
catch setupException
    try
        localCloseCurrentProject;
    catch cleanupException
        setupException = addCause(setupException, cleanupException);
    end
    rethrow(setupException);
end
end

function localAssertWorkspace
assert(evalin("base", "exist('Control','var') == 1") && ...
    evalin("base", "exist('Rover','var') == 1") && ...
    evalin("base", "exist('arm_q0','var') == 1") && ...
    evalin("base", "exist('rover_path1','var') == 1") && ...
    evalin("base", "exist('rover_path2','var') == 1") && ...
    evalin("base", "exist('rover_path','var') == 1") && ...
    evalin("base", "exist('sample_position','var') == 1") && ...
    evalin("base", "exist('mars_terrain_grid','var') == 1") && ...
    evalin("base", "exist('eeConfig','var') == 1") && ...
    evalin("base", "exist('ks_mars_rover','var') == 1"), ...
    "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
    "Official project StartUp did not define the native workspace.");
assert(isstruct(evalin("base", "Control")) && ...
    isstruct(evalin("base", "Rover")) && ...
    isstruct(evalin("base", "rover_path1")) && ...
    isstruct(evalin("base", "rover_path2")) && ...
    isstruct(evalin("base", "rover_path")) && ...
    isstruct(evalin("base", "mars_terrain_grid")) && ...
    isnumeric(evalin("base", "arm_q0")) && ...
    isnumeric(evalin("base", "sample_position")), ...
    "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
    "Official project StartUp produced an invalid native workspace.");
end

function localApplyScenario(model, scenario)
evalin("base", "rover_path = rover_path1;");
mars_terrain_set_z(char(string(scenario.terrain)));

Rover = evalin("base", "Rover");
Rover.Wheel_Surface.Friction.mu_static = ...
    double(scenario.TerrainMuStatic);
Rover.Wheel_Surface.Friction.mu_dynamic = ...
    double(scenario.TerrainMuDynamic);
assignin("base", "Rover", Rover);
Control = evalin("base", "Control");
Control.Drive.TargetSpeed = double(scenario.TargetSpeed_mps);
assignin("base", "Control", Control);

roverPath = evalin("base", "rover_path");
terrain = evalin("base", "mars_terrain_grid");
sample = evalin("base", "sample_position");
assignin("base", "RoverPath_XYZ", ...
    [roverPath.x(:), roverPath.y(:), roverPath.z(:)]);
assignin("base", "TerrainGrid_X_m", double(terrain.xg(:)'));
assignin("base", "TerrainGrid_Y_m", double(terrain.yg(:)'));
assignin("base", "TerrainGrid_Z_m", double(terrain.z_heights));
assignin("base", "SamplePosition_m", double(sample(:)'));
assignin("base", "TargetSpeed_mps", double(scenario.TargetSpeed_mps));
assignin("base", "TerrainMuStatic", double(scenario.TerrainMuStatic));
assignin("base", "TerrainMuDynamic", double(scenario.TerrainMuDynamic));

powertrain = model + "/Rover/Chassis/Powertrain";
assert(getSimulinkBlockHandle(powertrain, false) > 0, ...
    "SimuVerity:ReferenceSetup:ElectricalVariantMissing", ...
    "The native Mars rover electrical powertrain variant is missing.");
set_param(powertrain, "popup_powertrain", "Electrical");
set_param(model + "/Rover", "AttributesFormatString", ...
    get_param(powertrain, "LabelModeActiveChoice"));
assert(string(get_param(powertrain, "LabelModeActiveChoice")) == ...
    "Electrical", ...
    "SimuVerity:ReferenceSetup:ElectricalVariantMismatch", ...
    "The native Mars rover electrical powertrain variant did not activate.");
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "A repository-bundled Mars rover initialization asset is missing or changed: %s", ...
    pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function localCloseCurrentProject
try
    project = currentProject;
    if ~isempty(project)
        close(project);
    end
catch cleanupException
    if strcmp(cleanupException.identifier, ...
            "MATLAB:project:api:NoProjectCurrentlyLoaded")
        return
    end
    rethrow(cleanupException);
end
end
