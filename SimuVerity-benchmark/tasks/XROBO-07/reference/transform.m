function report = transform(sourceDir, destinationDir)
%TRANSFORM Materialize a task-facing wrapper around the official TEB model.
arguments
    sourceDir (1,1) string
    destinationDir (1,1) string
end
assert(isfolder(sourceDir), "SimuVerity:Importer:MissingSource", ...
    "R2025a source directory was not found: %s", sourceDir);
assert(~strcmpi(char(sourceDir), char(destinationDir)), ...
    "SimuVerity:Importer:InPlaceForbidden", ...
    "Importer must write to a separate cache directory.");
if ~isfolder(destinationDir), mkdir(destinationDir); end
copyfile(fullfile(sourceDir, "*"), destinationDir);
loggerSource = fullfile(fileparts(mfilename("fullpath")), ...
    "simuverity_xrobo07_robot_state_logger.m");
assert(isfile(loggerSource), "SimuVerity:Importer:LoggerMissing", ...
    "The public robot-state measurement logger is missing.");
copyfile(loggerSource, destinationDir);

matches = dir(fullfile(destinationDir, "**", "PathFollowingTEB.slx"));
assert(numel(matches) == 1, "SimuVerity:Importer:SourceModel", ...
    "Expected exactly one R2025a PathFollowingTEB.slx source model.");
sourceModel = string(fullfile(matches(1).folder, matches(1).name));
targetModel = fullfile(destinationDir, ...
    "PathFollowingTEB_SimuVerityReference.slx");
[~, model] = fileparts(sourceModel);

oldPath = path;
pathCleanup = onCleanup(@() path(oldPath)); %#ok<NASGU>
addpath(fileparts(sourceModel), "-begin");
% openExample may leave the source diagram loaded from its temporary workDir.
% Reload the verified copy so the wrapper is never saved back into that tree.
if bdIsLoaded(model), close_system(model, 0); end
load_system(sourceModel);
modelCleanup = onCleanup(@() localCloseModel(model)); %#ok<NASGU>

paths = localModelPaths(model);
localBindPublicInputs(model, paths);
localInstallPublicOutputs(model, paths);
set_param(paths.visualization, "Commented", "on");
set_param(paths.plot_exit, "Commented", "on");
set_param(model, ...
    "ReturnWorkspaceOutputs", "on", ...
    "StopTime", "100", ...
    "SignalLogging", "on", ...
    "LimitDataPoints", "off");
save_system(model, targetModel);
localNormalizeSlx(targetModel, sourceModel);

report = struct( ...
    "task_id", "F90-XROBO-07", ...
    "status", "PUBLIC_IO_REFERENCE_WRAPPER_COMPLETE", ...
    "source_entrypoint", "PathFollowingTEB.slx", ...
    "entrypoint", "PathFollowingTEB_SimuVerityReference.slx", ...
    "core_planner_modifications", 0, ...
    "vehicle_plant_modifications", 0, ...
    "input_bindings", 7, ...
    "map_source_bindings", 2, ...
    "measurement_outputs", ["robot_state", ...
        "executed_command", "planner_state"], ...
    "measurement_logger_file", ...
        "simuverity_xrobo07_robot_state_logger.m", ...
    "goal_termination_pass_through_added", true);
end

