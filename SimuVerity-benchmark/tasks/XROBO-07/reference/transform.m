function localBindMapConsumers(model)
charts = find(sfroot, "-isa", "Stateflow.EMChart");
changed = 0;
for index = 1:numel(charts)
    if ~startsWith(string(charts(index).Path), string(model) + "/")
        continue
    end
    script = string(charts(index).Script);
    if contains(script, "offroadMap.mat")
        if contains(script, "persistent globalMap localMap")
            script = regexprep(script, ...
                'data\s*=\s*load\("offroadMap\.mat","map"\);', ...
                '');
            script = regexprep(script, ...
                'globalMap\s*=\s*binaryOccupancyMap\(data\.map\);', ...
                'globalMap = binaryOccupancyMap(double(MapMatrix));');
        elseif contains(script, "persistent refPath mapMatrix resolution")
            script = regexprep(script, ...
                'data\s*=\s*load\([^;]*offroadMap\.mat[^;]*\);\s*mapMatrix\s*=\s*data\.map;', ...
                'mapMatrix = double(MapMatrix);');
        else
            error("SimuVerity:Importer:MapBindings", ...
                "An unexpected official map consumer was found: %s", ...
                charts(index).Path);
        end
        assert(~contains(script, "offroadMap.mat"), ...
            "SimuVerity:Importer:MapBindings", ...
            "A file-backed map dependency remains in %s.", charts(index).Path);
        charts(index).Script = char(script);
        localAddMapParameter(charts(index));
        changed = changed + 1;
    end
end
assert(changed == 2, "SimuVerity:Importer:MapBindings", ...
    "Expected exactly two official map consumers, found %d.", changed);
end

function localAddMapParameter(chart)
existing = find(chart, "-isa", "Stateflow.Data", "Name", "MapMatrix");
assert(isempty(existing), "SimuVerity:Importer:MapBindings", ...
    "MapMatrix is already declared in %s.", chart.Path);
parameter = Stateflow.Data(chart);
parameter.Name = "MapMatrix";
parameter.Scope = "Parameter";
parameter.Props.Array.Size = "[251 251]";
parameter.DataType = "uint8";
end

function localInstallPublicOutputs(model, paths)
robotMux = model + "/SimuVerity Robot State";
robotPort = model + "/robot_state";
robotLogger = model + "/SimuVerity robot_state logger";
commandSink = model + "/SimuVerity executed_command";
plannerFunction = model + "/SimuVerity Goal and Planner State";
plannerSink = model + "/SimuVerity planner_state";
plannerConversions = [ ...
    model + "/SimuVerity Goal Cast", ...
    model + "/SimuVerity Feasible Cast", ...
    model + "/SimuVerity Exit Cast", ...
    model + "/SimuVerity Replan Cast"];

add_block("simulink/Signal Routing/Mux", robotMux, ...
    "Inputs", "2", "Position", [380 780 410 840]);
add_block("simulink/Sinks/Out1", robotPort, ...
    "Port", "1", "Position", [455 785 485 805]);
add_block("simulink/User-Defined Functions/Level-2 MATLAB S-Function", ...
    robotLogger, ...
    "FunctionName", "simuverity_xrobo07_robot_state_logger", ...
    "Position", [455 825 650 855]);
localAddWorkspaceSink(commandSink, "executed_command", ...
    [255 720 425 750]);
add_block("simulink/User-Defined Functions/MATLAB Function", ...
    plannerFunction, "Position", [555 525 735 665]);
localSetPlannerFunction(plannerFunction);
localAddWorkspaceSink(plannerSink, "planner_state", [790 620 930 650]);
for index = 1:numel(plannerConversions)
    add_block("simulink/Signal Attributes/Data Type Conversion", ...
        plannerConversions(index), "OutDataTypeStr", "double", ...
        "Position", [465, 535 + 32 * (index - 1), ...
        505, 555 + 32 * (index - 1)]);
end

localConnect(model, paths.transpose, 1, robotMux, 1);
localConnect(model, paths.unit_delay_velocity, 1, robotMux, 2);
localConnect(model, robotMux, 1, robotPort, 1);
localConnect(model, robotMux, 1, robotLogger, 1);
localConnect(model, paths.selector, 1, commandSink, 1);

stopPorts = get_param(paths.stop, "PortHandles");
oldStopLine = get_param(stopPorts.Inport(1), "Line");
assert(oldStopLine > 0, "SimuVerity:Importer:GoalTermination", ...
    "The official goal-termination line is missing.");
delete_line(oldStopLine);
plannerSources = [paths.bus_selector, paths.bus_selector, ...
    paths.bus_selector, paths.process];
plannerPorts = [1, 2, 3, 4];
for index = 1:numel(plannerConversions)
    localConnect(model, plannerSources(index), plannerPorts(index), ...
        plannerConversions(index), 1);
    localConnect(model, plannerConversions(index), 1, ...
        plannerFunction, index);
end
localConnect(model, plannerFunction, 1, paths.stop, 1);
localConnect(model, plannerFunction, 2, plannerSink, 1);
end

function localSetPlannerFunction(block)
chart = find(sfroot, "-isa", "Stateflow.EMChart", "Path", char(block));
assert(numel(chart) == 1, "SimuVerity:Importer:PlannerTap", ...
    "Unable to resolve the task-facing planner-state MATLAB Function.");
chart.Script = char(join([ ...
    "function [terminalSignal,plannerState] = fcn(" + ...
        "goalReached,lastFeasible,exitFlag,replanRequest)", ...
    "terminalSignal = logical(goalReached);", ...
    "plannerState = zeros(4,1);", ...
    "plannerState(1) = terminalSignal;", ...
    "plannerState(2) = double(lastFeasible);", ...
    "plannerState(3) = double(exitFlag);", ...
    "plannerState(4) = double(replanRequest);", ...
    "end"], newline));
end

function localAddWorkspaceSink(block, variable, position)
add_block("simulink/Sinks/To Workspace", block, ...
    "VariableName", variable, ...
    "SaveFormat", "Timeseries", ...
    "MaxDataPoints", "inf", ...
    "Position", position);
end

function localConnect(parent, source, outputIndex, destination, inputIndex)
sourcePorts = get_param(source, "PortHandles");
destinationPorts = get_param(destination, "PortHandles");
assert(numel(sourcePorts.Outport) >= outputIndex && ...
    numel(destinationPorts.Inport) >= inputIndex, ...
    "SimuVerity:Importer:PortLookup", ...
    "A required task-facing instrumentation port is missing.");
add_line(parent, sourcePorts.Outport(outputIndex), ...
    destinationPorts.Inport(inputIndex), "autorouting", "on");
end

function localCloseModel(model)
try
    if bdIsLoaded(model), close_system(model, 0); end
catch
end
end

function localNormalizeSlx(modelPath, sourceModelPath)
% Normalize save-as-only metadata and ZIP timestamps for a stable archive.
temporary = string(modelPath) + ".normalizing";
assert(~isfile(temporary), "SimuVerity:Importer:NormalizeReuse", ...
    "SLX normalization output already exists: %s", temporary);
input = java.util.zip.ZipInputStream(java.io.BufferedInputStream( ...
    java.io.FileInputStream(char(modelPath))));
output = java.util.zip.ZipOutputStream(java.io.BufferedOutputStream( ...
    java.io.FileOutputStream(char(temporary))));
streamCleanup = onCleanup(@() localCloseZipStreams(input, output)); %#ok<NASGU>
fixedTimeMilliseconds = int64(946684800000); % 2000-01-01T00:00:00Z
sourceThumbnail = localReadZipEntry(sourceModelPath, ...
    "metadata/thumbnail.png");
while true
    sourceEntry = input.getNextEntry();
    if isempty(sourceEntry), break; end
    name = string(sourceEntry.getName());
    payload = javaMethod("toByteArray", ...
        "org.apache.commons.io.IOUtils", input);
    if name == "metadata/thumbnail.png"
        payload = sourceThumbnail;
    elseif name == "metadata/coreProperties.xml"
        raw = reshape(typecast(payload, "uint8"), 1, []);
        text = string(native2unicode(raw, "UTF-8"));
        text = regexprep(text, ...
            '<dcterms:modified xsi:type="dcterms:W3CDTF">[^<]+</dcterms:modified>', ...
            '<dcterms:modified xsi:type="dcterms:W3CDTF">2000-01-01T00:00:00Z</dcterms:modified>');
        payload = typecast(unicode2native(char(text), "UTF-8"), "int8");
    elseif name == "simulink/blockdiagram.xml"
        raw = reshape(typecast(payload, "uint8"), 1, []);
        text = string(native2unicode(raw, "UTF-8"));
        text = regexprep(text, '<P Name="ModelUUID">[^<]+</P>', ...
            '<P Name="ModelUUID">5f900007-0000-4000-8000-000000000007</P>');
        payload = typecast(unicode2native(char(text), "UTF-8"), "int8");
    elseif name == "simulink/windowsInfo.xml"
        raw = reshape(typecast(payload, "uint8"), 1, []);
        text = string(native2unicode(raw, "UTF-8"));
        text = regexprep(text, ...
            '<P Name="BDUuid" Class="char">[^<]+</P>', ...
            '<P Name="BDUuid" Class="char">5f900007-0000-4000-8000-000000000007</P>');
        payload = typecast(unicode2native(char(text), "UTF-8"), "int8");
    end
    targetEntry = java.util.zip.ZipEntry(char(name));
    targetEntry.setTime(fixedTimeMilliseconds);
    output.putNextEntry(targetEntry);
    if numel(payload) > 0, output.write(payload, 0, numel(payload)); end
    output.closeEntry();
    input.closeEntry();
end
output.finish();
output.close();
input.close();
movefile(temporary, modelPath, "f");
end

function payload = localReadZipEntry(archivePath, expectedName)
input = java.util.zip.ZipInputStream(java.io.BufferedInputStream( ...
    java.io.FileInputStream(char(archivePath))));
inputCleanup = onCleanup(@() input.close()); %#ok<NASGU>
payload = [];
while true
    entry = input.getNextEntry();
    if isempty(entry), break; end
    if string(entry.getName()) == string(expectedName)
        payload = javaMethod("toByteArray", ...
            "org.apache.commons.io.IOUtils", input);
        input.closeEntry();
        break
    end
    input.closeEntry();
end
assert(~isempty(payload), "SimuVerity:Importer:NormalizeSource", ...
    "Required source SLX entry is missing: %s", expectedName);
end

function localCloseZipStreams(input, output)
try, input.close(); catch, end
try, output.close(); catch, end
end
