function f90_xrobo02_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xrobo02_reference_clean_replay_setup Run the official YuMi startup.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XROBO-02", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XROBO-02.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The YuMi source initializer may only run for the sealed reference.");
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == ...
        "present", ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMismatch", ...
    "The exact XROBO-02 official scenarios are missing or changed.");
document = jsondecode(fileread(officialScenariosPath));
expectedScenarioIds = [ ...
    "nominal", ...
    "heavy_low_limit", ...
    "opposite_corner", ...
    "fast_asymmetric_load", ...
    "interior_recovery"];
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5 && ...
    isequal(string({document.scenarios.id}), expectedScenarioIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XROBO-02 requires its exact five-scenario contract.");

originalFolder = string(pwd);
folderCleanup = onCleanup(@() cd(originalFolder)); %#ok<NASGU>
runtimeRoot = originalFolder;
candidateRoots = [runtimeRoot; ...
    fullfile(runtimeRoot, "Industrial-Robots-Simscape")];
relativeModel = fullfile("Robots", "abbYuMi", "Models", ...
    "sm_abbYuMi_trajectory.slx");
expectedModelBinding = ...
    "present";
matches = false(numel(candidateRoots), 1);
for index = 1:numel(candidateRoots)
    candidateModel = fullfile(candidateRoots(index), relativeModel);
    matches(index) = isfile(candidateModel) && ...
        localFileIdentity(candidateModel) == expectedModelBinding;
end
assert(nnz(matches) == 1, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The exact bundled Industrial-Robots-Simscape closure was not found uniquely.");
sourceRoot = candidateRoots(matches);
modelDir = fullfile(sourceRoot, "Robots", "abbYuMi", "Models");
geometryDir = fullfile(sourceRoot, "Robots", "abbYuMi", "Geometry");
scriptsDir = fullfile(sourceRoot, "Scripts");
modelPath = fullfile(sourceRoot, relativeModel);
initializer = fullfile(modelDir, "startup_sm_abbYuMi_trajectory.m");

% The official startup consumes these exact retained source assets.  The
% complete 725-file inventory binds the remaining robot and geometry closure.
localAssertAsset(modelPath, expectedModelBinding);
localAssertAsset(initializer, ...
    "present");
localAssertAsset(fullfile(modelDir, "sm_abbYuMi_trajectory_waypoints.mat"), ...
    "present");
localAssertAsset(fullfile(modelDir, "sm_abbYuMi_point_cloud_finger.m"), ...
    "present");
localAssertAsset(fullfile(scriptsDir, "Point_Cloud_Data_Brick.m"), ...
    "present");
localAssertAsset(fullfile(geometryDir, "abbyumi_finger.stl"), ...
    "present");

addpath(sourceRoot, "-begin");
addpath(scriptsDir, "-begin");
addpath(modelDir, "-begin");
addpath(geometryDir, "-begin");
modelName = "sm_abbYuMi_trajectory";
try
    % Execute the unchanged upstream initializer in the base workspace.  It
    % loads the authoritative waypoint MAT, derives both point clouds and
    % opens the nested source model.  Close that source model without saving
    % so the shared clean-replay helper can load its byte-identical root alias.
    evalin("base", "run('" + replace(initializer, "'", "''") + "')");
    assert(bdIsLoaded(modelName), ...
        "SimuVerity:ReferenceSetup:OfficialModelNotLoaded", ...
        "The official YuMi initializer did not open its source model.");
    loadedModelPath = string(get_param(modelName, "FileName"));
    assert(strlength(loadedModelPath) > 0 && isfile(loadedModelPath) && ...
        localSamePath(loadedModelPath, modelPath) && ...
        localFileIdentity(loadedModelPath) == expectedModelBinding, ...
        "SimuVerity:ReferenceSetup:OfficialModelIdentityMismatch", ...
        "The official YuMi initializer opened a changed or unbound model.");
    assert(evalin("base", "exist('waypointsL','var') == 1") && ...
        isequal(size(evalin("base", "waypointsL")), [7 14]) && ...
        evalin("base", "all(isfinite(waypointsL(:)))") && ...
        evalin("base", "exist('waypointsR','var') == 1") && ...
        isequal(size(evalin("base", "waypointsR")), [7 14]) && ...
        evalin("base", "all(isfinite(waypointsR(:)))") && ...
        evalin("base", "exist('cube_l','var') == 1 && cube_l == 0.02") && ...
        evalin("base", "exist('brick_point_cloud','var') == 1 && size(brick_point_cloud,2) == 3") && ...
        evalin("base", "exist('finger_point_cloud','var') == 1 && size(finger_point_cloud,2) == 3") && ...
        evalin("base", "exist('segment_duration','var') == 1 && segment_duration == 2"), ...
        "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
        "The official YuMi initializer did not create its complete workspace contract.");
    close_system(modelName, 0);
catch setupException
    if bdIsLoaded(modelName)
        close_system(modelName, 0);
    end
    rethrow(setupException);
end
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "A repository-bundled YuMi initialization asset is missing or changed: %s", ...
    pathValue);
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
