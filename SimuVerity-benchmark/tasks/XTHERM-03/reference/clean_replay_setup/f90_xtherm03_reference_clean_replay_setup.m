function f90_xtherm03_reference_clean_replay_setup( ...
        taskId, officialScenariosPath, model)
%f90_xtherm03_reference_clean_replay_setup Disable original plot callback.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end
assert(taskId == "F90-XTHERM-03", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XTHERM-03.");
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The exact current XTHERM-03 official scenarios are required.");
document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["nominal", "cold_feed_step", "hot_feed_step", ...
    "low_recycle_step", "high_recycle_step", ...
    "combined_hot_low_recycle"];
assert(string(document.task_id) == "F90-XTHERM-03" && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 6 && ...
    isequal(string({document.scenarios.id}), expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The XTHERM-03 scenario identity or ordering differs.");

assert(model == "MSFcascade" && bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelNotLoaded", ...
    "The exact MSFcascade reference alias must already be loaded.");
modelPath = string(get_param(model, "FileName"));
expectedModelBinding = ...
    "present";
assert(isfile(modelPath) && localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceIdentity", ...
    "The loaded model is not the current XTHERM-03 reference.");
assert(string(get_param(model, "StopFcn")) == "msfplot", ...
    "SimuVerity:ReferenceSetup:CallbackMismatch", ...
    "The current reference StopFcn is not the expected original msfplot callback.");

set_param(model, "StopFcn", "");
assert(strlength(string(get_param(model, "StopFcn"))) == 0, ...
    "SimuVerity:ReferenceSetup:CallbackNotCleared", ...
    "The original reference StopFcn was not cleared in evaluator memory.");
assert(localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceModified", ...
    "Clearing the in-memory StopFcn changed the sealed reference file.");
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
