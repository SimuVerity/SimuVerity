function ext_xmech_wheelloader_reference_clean_replay_setup(taskId, officialScenariosPath)
%EXT_XMECH_WHEELLOADER_REFERENCE_CLEAN_REPLAY_SETUP Run official StartUp.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "EXT-XMECH-WHEELLOADER-COORD-01", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to EXT-XMECH-WHEELLOADER-COORD-01.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The wheel-loader project may initialize only the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
document = jsondecode(fileread(officialScenariosPath));
expectedScenarioIds = [ ...
    "nominal_y_cycle", ...
    "low_friction", ...
    "heavy_payload", ...
    "pump_derate", ...
    "low_hrb_precharge", ...
    "combined_robust"];
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 6 && ...
    isequal(string({document.scenarios.id}), expectedScenarioIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "Wheel-loader reference replay requires its exact six-scenario contract.");

originalFolder = string(pwd);
folderCleanup = onCleanup(@() cd(originalFolder)); %#ok<NASGU>
candidateRoots = [originalFolder; fullfile(originalFolder, "src")];
expectedProjectBinding = ...
    "present";
matches = false(numel(candidateRoots), 1);
for index = 1:numel(candidateRoots)
    candidateProject = fullfile(candidateRoots(index), ...
        "Wheel_Loader_Simscape.prj");
    matches(index) = isfile(candidateProject) && ...
        localFileIdentity(candidateProject) == expectedProjectBinding;
end
assert(nnz(matches) == 1, ...
    "SimuVerity:ReferenceSetup:ProjectClosureMismatch", ...
    "The exact bundled wheel-loader project was not found uniquely.");
projectRoot = candidateRoots(matches);
projectFile = fullfile(projectRoot, "Wheel_Loader_Simscape.prj");
modelPath = fullfile(projectRoot, "Models", "Vehicle", ...
    "sm_wheel_loader.slx");
startupDeclaration = fullfile(projectRoot, "resources", "project", ...
    "KAXfQgCar2Yb8zOxgvf9hdmLP1E", ...
    "XfQyIRgAx54Mt0gFJKIuEv2BWVQd.xml");
startupScript = fullfile(projectRoot, "Scripts_Data", ...
    "startup_sm_wheel_loader.m");
parameterScript = fullfile(projectRoot, "Scripts_Data", ...
    "sm_wheel_loader_params.m");
cylinderData = fullfile(projectRoot, "Scripts_Data", ...
    "sm_wheel_loader_test_cylinder_traj.mat");
operatorData = fullfile(projectRoot, "Scripts_Data", ...
    "sm_wheel_loader_test_operator_cmd.mat");

localAssertAsset(projectFile, expectedProjectBinding);
localAssertAsset(modelPath, ...
    "present");
localAssertAsset(startupDeclaration, ...
    "present");
localAssertAsset(startupScript, ...
    "present");
localAssertAsset(parameterScript, ...
    "present");
localAssertAsset(cylinderData, ...
    "present");
localAssertAsset(operatorData, ...
    "present");
declaration = string(fileread(startupDeclaration));
assert(contains(declaration, ...
        'File="Scripts_Data/startup_sm_wheel_loader.m"') && ...
    contains(declaration, 'Type="StartUp"'), ...
    "SimuVerity:ReferenceSetup:ProjectStartupMismatch", ...
    "The exact official wheel-loader StartUp declaration changed.");

try
    cd(projectRoot);
    project = openProject(projectFile);
    assert(localSamePath(string(project.RootFolder), projectRoot), ...
        "SimuVerity:ReferenceSetup:ProjectRootMismatch", ...
        "Official project root differs from the repository-bundled closure.");
    assert(evalin("base", "exist('HMPST','var') == 1") && ...
        isstruct(evalin("base", "HMPST")) && ...
        evalin("base", "exist('HydFcnParams','var') == 1") && ...
        isstruct(evalin("base", "HydFcnParams")) && ...
        evalin("base", "exist('testInput','var') == 1") && ...
        isstruct(evalin("base", "testInput")) && ...
        evalin("base", "isfield(testInput,'Active')") && ...
        evalin("base", "exist('stopTime','var') == 1") && ...
        evalin("base", "double(stopTime) == 70"), ...
        "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
        "Official wheel-loader StartUp did not initialize its workspace contract.");
    localAssertAsset(modelPath, ...
        "present");
catch setupException
    try
        localCloseCurrentProject;
    catch cleanupException
        setupException = addCause(setupException, cleanupException);
    end
    rethrow(setupException);
end
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "A repository-bundled wheel-loader initialization asset is missing or changed: %s", ...
    pathValue);
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
function localCloseCurrentProject
try
    project = currentProject;
    if ~isempty(project)
        close(project);
    end
catch cleanupException
    if strcmp(cleanupException.identifier, ...
            "MATLAB:project:api:NoProjectCurrentlyLoaded")
        return
    end
    rethrow(cleanupException);
end
end
