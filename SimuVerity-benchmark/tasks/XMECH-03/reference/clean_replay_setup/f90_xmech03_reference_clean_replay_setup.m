function f90_xmech03_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xmech03_reference_clean_replay_setup Initialize the exact DCT reference.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XMECH-03", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMECH-03.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The native dual-clutch workspace may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["urban_short_nominal"; "eudc_nominal"; ...
    "ftp_transient_nominal"; "urban_short_heavy"; ...
    "urban_short_clutch_derated"];
assert(isstruct(document) && isscalar(document) && ...
    isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && ...
    numel(document.scenarios) == numel(expectedIds) && ...
    isequal(string({document.scenarios.id}).', expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XMECH-03 requires its exact five-scenario contract.");

runtimeRoot = string(pwd);
sourceRoot = fullfile(runtimeRoot, "Simscape-Dual-Clutch");
modelPath = fullfile(sourceRoot, "Dual_Clutch_Trans.slx");
parameterPath = fullfile(sourceRoot, "Scripts_Data", "DCT_Model_PARAM.m");
calibrationPath = fullfile(sourceRoot, "Libraries", "Engine", ...
    "MBC_Engine_Calibrations.m");
localAssertAsset(modelPath, ...
    "present");
localAssertAsset(parameterPath, ...
    "present");
localAssertAsset(calibrationPath, ...
    "present");

command = evalin("base", "speed_command");
mass = double(evalin("base", "vehicle_mass_kg"));
capacity = double(evalin("base", "clutch_capacity_scale"));
assert(isa(command, "timeseries") && ...
    numel(command.Time) >= 2 && numel(command.Data) == numel(command.Time), ...
    "SimuVerity:ReferenceSetup:PublicInputContract", ...
    "speed_command must be a nonempty scalar timeseries.");
time = double(command.Time(:));
speed = double(command.Data(:));
assert(all(isfinite(time)) && all(isfinite(speed)) && ...
    time(1) == 0 && all(diff(time) > 0) && ...
    isscalar(mass) && isfinite(mass) && mass > 0 && ...
    isscalar(capacity) && isfinite(capacity) && capacity > 0, ...
    "SimuVerity:ReferenceSetup:PublicInputContract", ...
    "The XMECH-03 nominal public inputs are invalid.");

% Preserve the mature reference extractor's native initialization exactly.
% The generic clean replay already placed the three public inputs in the
% base workspace; this hook only maps them to the official model's names.
addpath(genpath(sourceRoot), "-begin");
assignin("base", "DCT_Model_HomeDir", char(sourceRoot));
localRunInBase(parameterPath);
localRunInBase(calibrationPath);
assert(evalin("base", "exist('DCT_Param','var') == 1"), ...
    "SimuVerity:ReferenceSetup:OfficialInitializationIncomplete", ...
    "The official DCT parameter script did not define DCT_Param.");
parameters = evalin("base", "DCT_Param");
parameters.Vehicle.Mass = mass;
parameters.Clutch.Derating_Factor = capacity;
selectedCycle = struct( ...
    "time", double(command.Time(:)), ...
    "SpdKph", double(command.Data(:)));
assignin("base", "DCT_Param", parameters);
assignin("base", "UrbanCycle7", selectedCycle);
assignin("base", "Drive_Cycle_Num", 7);
end

function localRunInBase(file)
command = "run('" + replace(string(file), "'", "''") + "');";
evalin("base", command);
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled XMECH-03 asset is missing or changed: %s", pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
