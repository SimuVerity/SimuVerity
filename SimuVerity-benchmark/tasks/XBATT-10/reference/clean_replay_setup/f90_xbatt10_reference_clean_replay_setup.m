function f90_xbatt10_reference_clean_replay_setup( ...
        taskId, officialScenariosPath, model)
%F90_XBATT10_REFERENCE_CLEAN_REPLAY_SETUP Map the public nominal input.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end

assert(taskId == "F90-XBATT-10", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XBATT-10.");
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The exact current XBATT-10 official scenarios are required.");
document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["baseline", "heavy_mass", "low_soc", ...
    "low_power_heavy", "high_power_heavy", "regen_off"];
assert(string(document.task_id) == "F90-XBATT-10" && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 6 && ...
    isequal(string({document.scenarios.id}), expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The XBATT-10 scenario identity or ordering differs.");

assert(model == "EV_Truck_Model" && bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelNotLoaded", ...
    "The exact XBATT-10 reference model must already be loaded.");
modelPath = string(get_param(model, "FileName"));
expectedModelBinding = ...
    "present";
[~, modelFileName, modelExtension] = fileparts(modelPath);
assert(modelFileName + modelExtension == "EV_Truck_Model.slx" && ...
    isfile(modelPath) && localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceIdentity", ...
    "The loaded model is not the current XBATT-10 reference.");

modelDir = string(pwd);
assert(localSamePath(modelDir, fileparts(modelPath)), ...
    "SimuVerity:ReferenceSetup:ReferenceLocation", ...
    "The clean-replay working directory differs from the model directory.");
dataDir = fullfile(modelDir, "MATLAB Pre-defined Files");
assert(isfolder(dataDir) && isfile(fullfile(modelDir, "LICENSE")), ...
    "SimuVerity:ReferenceSetup:ReferenceClosure", ...
    "The evaluator-owned XBATT-10 runtime closure is incomplete.");
addpath(dataDir, "-begin");

assert(evalin("base", "exist('ev_truck_input','var') == 1"), ...
    "SimuVerity:ReferenceSetup:PublicNominalInput", ...
    "The evaluator-owned public nominal input is missing.");
publicInput = evalin("base", "ev_truck_input");
required = ["drive_cycle_time_s", "drive_cycle_speed_mps", ...
    "vehicle_mass_kg", "powertrain_rating_kw", ...
    "battery_initial_soc_fraction", "regenerative_braking_enabled"];
assert(isstruct(publicInput) && isscalar(publicInput) && ...
    all(isfield(publicInput, required)), ...
    "SimuVerity:ReferenceSetup:PublicNominalInput", ...
    "The public nominal input does not expose the current XBATT-10 fields.");
baseline = document.scenarios(1);
expectedTime = [0; 1; 2; 4; 6; 8; 10; 12];
expectedSpeed = [0; 0; 4; 10; 10; 6; 0; 0];
assert(isequal(double(publicInput.drive_cycle_time_s(:)), expectedTime) && ...
    isequal(double(publicInput.drive_cycle_speed_mps(:)), expectedSpeed) && ...
    double(publicInput.vehicle_mass_kg) == double(baseline.vehicle_mass_kg) && ...
    double(publicInput.powertrain_rating_kw) == ...
        double(baseline.powertrain_rating_kw) && ...
    double(publicInput.battery_initial_soc_fraction) == ...
        double(baseline.battery_initial_soc_fraction) && ...
    logical(publicInput.regenerative_braking_enabled) == ...
        logical(baseline.regenerative_braking_enabled), ...
    "SimuVerity:ReferenceSetup:PublicNominalInput", ...
    "The public nominal input differs from the current baseline scenario.");

assignin("base", "Veh_mass", double(publicInput.vehicle_mass_kg));
assignin("base", "Power_option", double(publicInput.powertrain_rating_kw));
assignin("base", "Batt_soc_init", ...
    double(publicInput.battery_initial_soc_fraction));
assignin("base", "Elec_aux_sw", 1);
assignin("base", "Elec_rgn_sw", ...
    double(logical(publicInput.regenerative_braking_enabled)));
assignin("base", "time", double(publicInput.drive_cycle_time_s(:)));
assignin("base", "speed", double(publicInput.drive_cycle_speed_mps(:)));
set_param(model, "StopTime", "12");
set_param(model, "LimitDataPoints", "off");

assert(localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceModified", ...
    "Initializing the native reference input changed the sealed model.");
end

function same = localSamePath(first, second)
first = strrep(char(first), '/', filesep);
second = strrep(char(second), '/', filesep);
if ispc
    same = strcmpi(first, second);
else
    same = strcmp(first, second);
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
