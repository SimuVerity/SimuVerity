function f90_xaero02_reference_clean_replay_setup(taskId, officialScenariosPath)
%F90_XAERO02_REFERENCE_CLEAN_REPLAY_SETUP Run the source-owned Funray initializer.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XAERO-02", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XAERO-02.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The native XAERO-02 workspace may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XAERO-02 requires its exact five-scenario contract.");

assetRoot = string(pwd);
modelPath = fullfile(assetRoot, "Plane", "models", ...
    "AirplaneSimModel_LindiPlane.slx");
funrayRoot = fullfile(assetRoot, "Plane", "Funray");
initPath = fullfile(funrayRoot, "init_Funray_LindiPlane.m");

% The authoritative initializer invokes this exact source-owned bootstrap
% chain before creating the airplane, environment, joystick, and Lindi
% workspace.  Bind every bootstrap hop plus each direct initializer input;
% the retained reference inventory binds the rest of the transitive closure.
localAssertAsset(modelPath, ...
    "present");
localAssertAsset(initPath, ...
    "present");
localAssertAsset(fullfile(funrayRoot, "addPathFunray.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "Plane", "addPathPlane.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "common_functions", ...
    "addPathLadacExamples.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "libraries", ...
    "m-utils", "test_framework", "clc_clear.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "libraries", ...
    "m-utils", "test_framework", "open_model.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "aircraft", ...
    "airplanes", "complete", "conventional_airplane_single_engine", ...
    "conventionalAirplaneLoadParams.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "environment", ...
    "envirLoadParams.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "control", ...
    "joystick", "joystickLoadParams.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "control", ...
    "autopilots", "LindiPlane", "lindiPlaneAutoCreate.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac-examples-data", ...
    "LADAC_params", "Funray", "airplane_params_Funray.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "environment", ...
    "envir_params_default.m"), ...
    "present");
localAssertAsset(fullfile(assetRoot, "modules", "ladac", "control", ...
    "joystick", "params", "joystick_params_Xbox_360.m"), ...
    "present");

% Match the native public reference extractor: expose only the bundled
% Funray bootstrap, select its non-interactive test branch, and execute the
% initializer itself.  No workspace value is reconstructed here.
originalFolder = string(pwd);
folderCleanup = onCleanup(@() cd(originalFolder)); %#ok<NASGU>
addpath(funrayRoot, "-begin");
assignin("base", "TEST_LADAC", true);
evalin("base", "run('" + replace(initPath, "'", "''") + "')");
requiredVariables = ["airplane", "envir", "jystck", "waypoints", ...
    "lindi", "lindi_notune"];
for index = 1:numel(requiredVariables)
    assert(evalin("base", "exist('" + requiredVariables(index) + ...
        "','var') == 1"), ...
        "SimuVerity:ReferenceSetup:OfficialInitializationIncomplete", ...
        "The official XAERO-02 initializer did not define %s.", ...
        requiredVariables(index));
end
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled XAERO-02 asset is missing or changed: %s", pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
