function f90_xfluid02_reference_clean_replay_setup( ...
        taskId, officialScenariosPath)
%f90_xfluid02_reference_clean_replay_setup Load the exact native project.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end

assert(taskId == "F90-XFLUID-02", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XFLUID-02.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The triplex-pump project may initialize only the sealed reference.");
localAssertAsset(officialScenariosPath, ...
    "present");
document = jsondecode(fileread(officialScenariosPath));
expectedScenarioIds = [ ...
    "low_speed_low_pressure", ...
    "high_speed_high_pressure", ...
    "seal_leak_cylinder2", ...
    "blocked_inlet_cylinder3", ...
    "paired_fault", ...
    "paired_control"];
scenarios = document.scenarios;
if iscell(scenarios), scenarios = [scenarios{:}]; end
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    numel(scenarios) == 6 && ...
    isequal(string({scenarios.id}), expectedScenarioIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XFLUID-02 requires its exact six-scenario contract.");

runtimeRoot = string(pwd);
projectRoot = fullfile(runtimeRoot, "Simscape-Triplex-Pump");
projectPath = fullfile(projectRoot, "Triplex_Pump.prj");
sourceModelPath = fullfile(projectRoot, "sm_pump_triplex.slx");
referenceModelPath = fullfile(projectRoot, "XFLUID02_reference.slx");
candidateAlias = fullfile(runtimeRoot, "XFLUID02_reference.slx");
startupPath = fullfile(projectRoot, "Scripts_Data", ...
    "startup_sm_pump_triplex.m");
parameterPath = fullfile(projectRoot, "Scripts_Data", ...
    "sm_pump_triplex_param.m");
startupDeclaration = fullfile(projectRoot, "resources", "project", ...
    "KAXfQgCar2Yb8zOxgvf9hdmLP1E", ...
    "piH3E-pD-z_56tryMZfvfK7EO30d.xml");

localAssertAsset(projectPath, ...
    "present");
localAssertAsset(sourceModelPath, ...
    "present");
localAssertAsset(referenceModelPath, ...
    "present");
localAssertAsset(candidateAlias, ...
    "present");
localAssertAsset(startupPath, ...
    "present");
localAssertAsset(parameterPath, ...
    "present");
localAssertAsset(startupDeclaration, ...
    "present");
declaration = string(fileread(startupDeclaration));
assert(contains(declaration, ...
        'File="Scripts_Data/startup_sm_pump_triplex.m"') && ...
    contains(declaration, 'Type="StartUp"'), ...
    "SimuVerity:ReferenceSetup:ProjectStartupMismatch", ...
    "The exact triplex-pump project StartUp declaration is missing.");

project = openProject(projectPath);
assert(localSamePath(string(project.RootFolder), projectRoot), ...
    "SimuVerity:ReferenceSetup:ProjectRootMismatch", ...
    "Official project root differs from the bound runtime closure.");
assert(evalin("base", "exist('TRP_Par','var') == 1") && ...
    evalin("base", "exist('pOutMeas_time','var') == 1") && ...
    evalin("base", "exist('pOutMeas_data','var') == 1"), ...
    "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
    "Official project StartUp did not initialize the triplex-pump workspace.");
localAssertAsset(sourceModelPath, ...
    "present");
localAssertAsset(referenceModelPath, ...
    "present");
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled triplex-pump asset is missing or changed: %s", ...
    pathValue);
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
