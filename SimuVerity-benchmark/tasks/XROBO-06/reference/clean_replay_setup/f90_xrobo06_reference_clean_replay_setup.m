function f90_xrobo06_reference_clean_replay_setup(taskId, officialScenariosPath, model)
%f90_xrobo06_reference_clean_replay_setup Initialize pretrained walker.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end
assert(taskId == "F90-XROBO-06", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XROBO-06.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);

assetRoot = string(pwd);
parameterScript = fullfile(assetRoot, "sm_humanoid_walker_rl_parameters.m");
agentFile = fullfile(assetRoot, "sm_humanoid_walker_saved_agent.mat");
libraryFile = fullfile(assetRoot, "sm_humanoid_walker_lib.slx");
assert(isfile(parameterScript) && isfile(agentFile) && isfile(libraryFile) && ...
    localFileIdentity(parameterScript) == ...
        "present" && ...
    localFileIdentity(agentFile) == ...
        "present" && ...
    localFileIdentity(libraryFile) == ...
        "present", ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled humanoid initialization closure is incomplete or changed.");
addpath(assetRoot, "-begin");
evalin("base", "run('" + replace(parameterScript, "'", "''") + "')");
evalin("base", "load('" + replace(agentFile, "'", "''") + ...
    "','saved_agent'); f90_reference_agent=saved_agent; params=params;");
assert(bdIsLoaded(model) && getSimulinkBlockHandle(model + "/RL Agent") > 0, ...
    "SimuVerity:ReferenceSetup:AgentBlockMissing", ...
    "The exact reference RL Agent block is unavailable.");
set_param(model + "/RL Agent", "Agent", "f90_reference_agent");
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
