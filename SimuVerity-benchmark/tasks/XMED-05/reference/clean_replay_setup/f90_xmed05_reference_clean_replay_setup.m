function f90_xmed05_reference_clean_replay_setup(taskId, officialScenariosPath, model)
%f90_xmed05_reference_clean_replay_setup Disable native GUI/file sinks in memory.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end
assert(taskId == "F90-XMED-05", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMED-05.");
assert(isfile(officialScenariosPath) && bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:Contract", ...
    "Official scenarios and the loaded reference model are required.");

expectedScenariosBinding = ...
    "present";
assert(localFileIdentity(officialScenariosPath) == expectedScenariosBinding, ...
    "SimuVerity:ReferenceSetup:ScenarioIdentity", ...
    "The official scenario contract is missing or changed.");
scenarioDocument = jsondecode(fileread(officialScenariosPath));
scenarios = scenarioDocument.scenarios;
if iscell(scenarios), scenarios = [scenarios{:}]; end
assert(~isempty(scenarios), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The official scenario contract has no reference scenario.");
scenario = scenarios(1);
assert(string(scenario.id) == "normal_delay" && ...
    double(scenario.RhythmCondition) == 0 && ...
    double(scenario.SimulationDuration_ms) == 8000 && ...
    string(scenario.reference_parameter_pack) == "models/parasNormal.mat" && ...
    isempty(fieldnames(scenario.reference_overrides)), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The first current reference scenario is missing or changed.");

expectedModelBinding = ...
    "present";
modelFile = string(get_param(model, "FileName"));
assert(isfile(modelFile) && localFileIdentity(modelFile) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ModelIdentity", ...
    "The loaded runtime model is not the exact current reference.");

submissionRoot = string(fileparts(modelFile));
referenceRoot = fullfile(submissionRoot, "PACER_v0.2.0");
configFile = fullfile(referenceRoot, "N3Cfg.mat");
dataFile = fullfile(referenceRoot, "N3Data.mat");
parameterPack = fullfile(referenceRoot, "models", "parasNormal.mat");
libraryFile = fullfile(referenceRoot, "Lib", "Libs.slx");
assetPaths = [configFile; dataFile; parameterPack; libraryFile];
assetBindings = [ ...
    "present"; ...
    "present"; ...
    "present"; ...
    "present"];
for assetIndex = 1:numel(assetPaths)
    assert(isfile(assetPaths(assetIndex)) && ...
        localFileIdentity(assetPaths(assetIndex)) == assetBindings(assetIndex), ...
        "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
        "A repository-bundled PACER initialization asset is missing or changed.");
end

setupRoot = string(fileparts(mfilename("fullpath")));
taskRoot = string(fileparts(fileparts(setupRoot)));
nativePath = fullfile(taskRoot, ...
    "vendor", "scripts", "formal90", "tasks", "f90_xmed05", ...
    "f90_xmed05_extract_evidence_foundation.m");
expectedNativeBinding = ...
    "present";
assert(isfile(nativePath) && localFileIdentity(nativePath) == expectedNativeBinding, ...
    "SimuVerity:ReferenceSetup:NativeAuthority", ...
    "The pinned native reference adapter is missing or changed.");

% Mirror the complete current reference initialization before compile.  The
% native path keeps PACER as cwd and loads these three MAT files into the
% base workspace before loading/updating the model; the clean replay process
% is isolated, so retaining that cwd/path state is intentional.
addpath(referenceRoot, fullfile(referenceRoot, "Lib"), ...
    fullfile(referenceRoot, "src"), fullfile(referenceRoot, "models"), ...
    "-begin");
cd(referenceRoot);
localLoadToBase(configFile);
localLoadToBase(dataFile);
localLoadToBase(parameterPack);
assignin("base", "RhythmCondition", double(scenario.RhythmCondition));
assignin("base", "SimulationDuration_ms", ...
    double(scenario.SimulationDuration_ms));
assert(evalin("base", "exist('cfgdata','var')") == 1 && ...
    evalin("base", "exist('pp','var')") == 1 && ...
    evalin("base", "exist('pNode','var')") == 1 && ...
    evalin("base", "exist('pPath','var')") == 1 && ...
    evalin("base", "exist('ppPath','var')") == 1 && ...
    evalin("base", "exist('pRange','var')") == 1, ...
    "SimuVerity:ReferenceSetup:WorkspaceContract", ...
    "The exact PACER parameter workspace was not initialized.");
if bdIsLoaded("Libs")
    loadedLibrary = string(get_param("Libs", "FileName"));
    assert(isfile(loadedLibrary) && localFileIdentity(loadedLibrary) == assetBindings(4), ...
        "SimuVerity:ReferenceSetup:LibraryIdentity", ...
        "A different PACER library is already loaded.");
else
    load_system(libraryFile);
end

% The current native reference extractor performs these exact in-memory
% mutations before its first update.  Clean replay must establish the same
% no-GUI/no-file boundary without opening Heart_GUI or saving the model.
guiBlocks = find_system(model, "LookUnderMasks", "all", ...
    "FollowLinks", "on", "BlockType", "S-Function", ...
    "FunctionName", "SaveTrace_sfcn");
assert(numel(guiBlocks) == 1 && string(guiBlocks{1}) == model + "/S-Function", ...
    "SimuVerity:ReferenceSetup:SaveTraceLocator", ...
    "Expected the exact current SaveTrace_sfcn block.");

fileBlocks = find_system(model, "SearchDepth", 1, "BlockType", "ToFile");
expectedFileBlocks = sort(model + ["/To File"; "/To File1"; "/To File2"]);
assert(isequal(sort(string(fileBlocks(:))), expectedFileBlocks), ...
    "SimuVerity:ReferenceSetup:FileSinkLocator", ...
    "The current top-level file sink set is missing or changed.");

set_param(guiBlocks{1}, "Commented", "on");
assert(string(get_param(guiBlocks{1}, "Commented")) == "on", ...
    "SimuVerity:ReferenceSetup:SaveTraceDisable", ...
    "The native GUI S-Function was not disabled in memory.");
for fileBlock = string(fileBlocks(:)).'
    set_param(char(fileBlock), "Commented", "on");
    assert(string(get_param(char(fileBlock), "Commented")) == "on", ...
        "SimuVerity:ReferenceSetup:FileSinkDisable", ...
        "A native file sink was not disabled in memory.");
end
end

function names = localLoadToBase(pathValue)
value = load(pathValue);
names = string(fieldnames(value));
for name = names.'
    assignin("base", char(name), value.(char(name)));
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
