function f90_xfluid04_reference_clean_replay_setup( ...
        taskId, officialScenariosPath)
%f90_xfluid04_reference_clean_replay_setup Load the exact native project.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end

assert(taskId == "F90-XFLUID-04", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XFLUID-04.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The hydraulic-lift project may initialize only the sealed reference.");
localAssertAsset(officialScenariosPath, ...
    "present");
document = jsondecode(fileread(officialScenariosPath));
expectedScenarioIds = [ ...
    "nominal", ...
    "low_supply_drop", ...
    "high_supply_rise", ...
    "high_target_boundary", ...
    "pressure_drop_pair", ...
    "pressure_control_pair"];
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 6 && ...
    isequal(string({document.scenarios.id}), expectedScenarioIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XFLUID-04 requires its exact six-scenario contract.");

runtimeRoot = string(pwd);
projectPath = fullfile(runtimeRoot, "Hydraulic_Lift.prj");
sourceModelPath = fullfile(runtimeRoot, "ssc_hydraulic_lift.slx");
referenceModelPath = fullfile(runtimeRoot, "XFLUID04_reference.slx");
startupPath = fullfile(runtimeRoot, "Scripts_Data", ...
    "startup_Hydraulic_Lift.m");
parameterPath = fullfile(runtimeRoot, "Scripts_Data", ...
    "Scissor_Lift_Model_PARAM.m");
scissorLibraryPath = fullfile(runtimeRoot, "Libraries", ...
    "Scissor_Parts_Lib.slx");
startupDeclaration = fullfile(runtimeRoot, "resources", "project", ...
    "KAXfQgCar2Yb8zOxgvf9hdmLP1E", ...
    "s272pqigNIsG33SKZ6U45JcjOksd.xml");

localAssertAsset(projectPath, ...
    "present");
localAssertAsset(sourceModelPath, ...
    "present");
localAssertAsset(referenceModelPath, ...
    "present");
localAssertAsset(startupPath, ...
    "present");
localAssertAsset(parameterPath, ...
    "present");
localAssertAsset(scissorLibraryPath, ...
    "present");
localAssertAsset(startupDeclaration, ...
    "present");
declaration = string(fileread(startupDeclaration));
assert(contains(declaration, ...
        'File="Scripts_Data/startup_Hydraulic_Lift.m"') && ...
    contains(declaration, 'Type="StartUp"'), ...
    "SimuVerity:ReferenceSetup:ProjectStartupMismatch", ...
    "The exact hydraulic-lift project StartUp declaration is missing.");

project = openProject(projectPath);
assert(localSamePath(string(project.RootFolder), runtimeRoot), ...
    "SimuVerity:ReferenceSetup:ProjectRootMismatch", ...
    "Official project root differs from the bound runtime closure.");
assert(evalin("base", "exist('Scissor_Lift_Param','var') == 1"), ...
    "SimuVerity:ReferenceSetup:OfficialStartupIncomplete", ...
    "Official project StartUp did not create Scissor_Lift_Param.");
assert(bdIsLoaded("ssc_hydraulic_lift"), ...
    "SimuVerity:ReferenceSetup:OfficialModelNotLoaded", ...
    "Official project StartUp did not load ssc_hydraulic_lift.");
loadedSourcePath = string(get_param("ssc_hydraulic_lift", "FileName"));
assert(localSamePath(loadedSourcePath, sourceModelPath) && ...
    localFileIdentity(loadedSourcePath) == ...
        "present", ...
    "SimuVerity:ReferenceSetup:OfficialModelIdentityMismatch", ...
    "Official project StartUp loaded a changed or unbound source model.");
close_system("ssc_hydraulic_lift", 0);
localAssertAsset(referenceModelPath, ...
    "present");
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled hydraulic-lift asset is missing or changed: %s", ...
    pathValue);
end

function same = localSamePath(leftPath, rightPath)
leftCanonical = string(java.io.File(char(leftPath)).getCanonicalPath());
rightCanonical = string(java.io.File(char(rightPath)).getCanonicalPath());
if ispc
    same = strcmpi(leftCanonical, rightCanonical);
else
    same = leftCanonical == rightCanonical;
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
