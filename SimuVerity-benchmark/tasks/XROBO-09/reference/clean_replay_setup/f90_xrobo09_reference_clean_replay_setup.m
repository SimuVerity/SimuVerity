function f90_xrobo09_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xrobo09_reference_clean_replay_setup Initialize official ASV demo.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XROBO-09", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XROBO-09.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);

assetRoot = string(pwd);
marineRoot = fullfile(assetRoot, "MarineVessel");
dataRoot = fullfile(marineRoot, "DataFile");
scripts = [ ...
    fullfile(dataRoot, "DataVesselPlatform.m"); ...
    fullfile(dataRoot, "DataInitialCondition.m"); ...
    fullfile(dataRoot, "DataSampleTime.m"); ...
    fullfile(dataRoot, "DataGuidance.m")];
expected = [ ...
    "present"; ...
    "present"; ...
    "present"; ...
    "present"];
assert(all(isfile(scripts)) && all(arrayfun(@(index) ...
    localFileIdentity(scripts(index)) == expected(index), (1:numel(scripts)).')), ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled ASV parameter scripts are incomplete or changed.");
addpath(genpath(marineRoot), "-begin");
for index = 1:numel(scripts)
    evalin("base", "run('" + replace(scripts(index), "'", "''") + "')");
end

document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "scenarios") && ~isempty(document.scenarios), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XROBO-09 requires at least one official scenario.");
scenario = document.scenarios(1);
scenarioPath = fullfile(marineRoot, string(scenario.scenario_mat));
assert(isfile(scenarioPath), ...
    "SimuVerity:ReferenceSetup:ScenarioAssetMismatch", ...
    "The repository-bundled exported ASV scenario is missing or changed.");
evalin("base", "load('" + replace(scenarioPath, "'", "''") + "')");
assignin("base", "waypoints_m", double(scenario.Waypoints_m));
assignin("base", "StopTime", double(scenario.stop_time_s));
assignin("base", "xlimits", [-150 110]);
assignin("base", "ylimits", [-10 180]);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
