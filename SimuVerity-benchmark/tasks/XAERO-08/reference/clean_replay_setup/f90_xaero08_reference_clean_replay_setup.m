function f90_xaero08_reference_clean_replay_setup(taskId, officialScenariosPath)
%F90_XAERO08_REFERENCE_CLEAN_REPLAY_SETUP Run the current rocket initializer.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XAERO-08", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XAERO-08.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The native rocket workspace may only initialize the exact reference.");

expectedScenarioBinding = ...
    "present";
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == expectedScenarioBinding, ...
    "SimuVerity:ReferenceSetup:ScenarioIdentity", ...
    "The official scenario contract is missing or changed.");
document = jsondecode(fileread(officialScenariosPath));
scenarios = document.scenarios;
if iscell(scenarios), scenarios = [scenarios{:}]; end
assert(string(document.task_id) == taskId && numel(scenarios) == 5, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XAERO-08 requires its exact five-scenario contract.");
scenario = scenarios(1);
assert(string(scenario.id) == "nominal" && ...
    double(scenario.mass_flow_kg_per_s) == 132 && ...
    double(scenario.payload_mass_kg) == 5000 && ...
    double(scenario.gravity_turn_angle_rad) == 0.1, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The current nominal rocket scenario is missing or changed.");

assetRoot = string(pwd);
sourceRoot = fullfile(assetRoot, "source", "simulink_stuff");
sourceModel = fullfile(assetRoot, "source", "simulink_stuff", "Rocket.slx");
candidateAlias = fullfile(assetRoot, "Rocket.slx");
initializer = fullfile(assetRoot, "source", "simulink_stuff", "Parameters.m");
expectedModelBinding = ...
    "present";
expectedInitializerBinding = ...
    "present";
assert(isfile(sourceModel) && isfile(candidateAlias) && ...
    localFileIdentity(sourceModel) == expectedModelBinding && ...
    localFileIdentity(candidateAlias) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ModelIdentity", ...
    "The staged rocket reference or its sealed alias is missing or changed.");
assert(isfile(initializer) && ...
    localFileIdentity(initializer) == expectedInitializerBinding, ...
    "SimuVerity:ReferenceSetup:InitializerIdentity", ...
    "The source-owned rocket initializer is missing or changed.");

% The current native reference extractor runs Parameters.m before
% load_system.  Reproduce that ordering exactly; do not reconstruct its
% workspace values or save either model copy.
addpath(sourceRoot, "-begin");
evalin("base", "run('" + replace(initializer, "'", "''") + "')");
massFlow = double(evalin("base", "m_dot"));
payload = double(evalin("base", "m_payload"));
dryMass = double(evalin("base", "m_dry"));
zeroFuelMass = double(evalin("base", "m_zfw"));
turnAngle = double(evalin("base", "gam_in"));
assert(massFlow == double(scenario.mass_flow_kg_per_s) && ...
    payload == double(scenario.payload_mass_kg) && ...
    zeroFuelMass == payload + dryMass && ...
    turnAngle == double(scenario.gravity_turn_angle_rad) && ...
    double(evalin("base", "mass_flow_kg_per_s")) == massFlow && ...
    double(evalin("base", "payload_mass_kg")) == payload && ...
    double(evalin("base", "gravity_turn_angle_rad")) == turnAngle, ...
    "SimuVerity:ReferenceSetup:OfficialInitializationIncomplete", ...
    "The source-owned rocket initializer does not match the nominal contract.");
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
