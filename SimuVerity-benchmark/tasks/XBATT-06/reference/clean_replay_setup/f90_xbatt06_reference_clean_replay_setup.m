function f90_xbatt06_reference_clean_replay_setup( ...
        taskId, officialScenariosPath, model)
%F90_XBATT06_REFERENCE_CLEAN_REPLAY_SETUP Initialize native reference data.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end

assert(taskId == "F90-XBATT-06", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XBATT-06.");
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The exact current XBATT-06 official scenarios are required.");
document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["nominal_long_flight", "cold_short_high_pulse", ...
    "hot_high_rms_flight", "moderate_profile_high_forecast", ...
    "aged_capacity_long_flight"];
assert(string(document.task_id) == "F90-XBATT-06" && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5 && ...
    isequal(string({document.scenarios.id}), expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The XBATT-06 scenario identity or ordering differs.");

assert(model == "BatteryEstim3RC_PTBS_EQ_RUL_v1" && bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelNotLoaded", ...
    "The exact XBATT-06 reference alias must already be loaded.");
modelPath = string(get_param(model, "FileName"));
expectedModelBinding = ...
    "present";
assert(isfile(modelPath) && localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceIdentity", ...
    "The loaded model is not the current XBATT-06 reference.");

referenceRoot = fullfile(fileparts(modelPath), "src");
parameterPath = fullfile(referenceRoot, "20230919_data_modelparams.mat");
performancePath = fullfile(referenceRoot, "20230919_data_performance.mat");
closureModel = fullfile(referenceRoot, ...
    "BatteryEstim3RC_PTBS_EQ_RUL_v1.slx");
assert(isfolder(referenceRoot) && isfile(parameterPath) && ...
    isfile(performancePath) && isfile(closureModel) && ...
    localFileIdentity(closureModel) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceClosure", ...
    "The evaluator-owned XBATT-06 native data closure is incomplete.");

parameters = load(parameterPath);
performance = load(performancePath);
assert(isfield(parameters, "mp") && isfield(performance, "xhat") && ...
    size(performance.xhat, 1) >= 7 && size(performance.xhat, 2) >= 2, ...
    "SimuVerity:ReferenceSetup:NativeData", ...
    "The evaluator-owned XBATT-06 native parameter data is incomplete.");
scenario = document.scenarios(1);
mp = localScenarioMp(parameters.mp, performance.xhat, scenario, referenceRoot);
assignin("base", "mp", mp);
set_param(model + "/Constant", "Value", ...
    sprintf("%.17g", double(scenario.temperature_K)));
set_param(model, "StopTime", sprintf("%.17g", mp.t(end)));

assert(localFileIdentity(modelPath) == expectedModelBinding && ...
    localFileIdentity(closureModel) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceModified", ...
    "Initializing native reference data changed a sealed reference model.");
end

function mp = localScenarioMp(baseMp, xhat, scenario, referenceRoot)
mp = baseMp;
index = double(scenario.dataset_index);
assert(index >= 1 && index <= numel(mp.fn) && ...
    string(mp.fn(index)) == string(scenario.dataset_file), ...
    "SimuVerity:ReferenceSetup:DatasetIdentity", ...
    "The nominal dataset differs from the pinned native driver list.");
datasetPath = fullfile(referenceRoot, "data", ...
    string(scenario.dataset_file));
assert(isfile(datasetPath), ...
    "SimuVerity:ReferenceSetup:DatasetMissing", ...
    "The nominal XBATT-06 flight dataset is missing.");
data = load(datasetPath);
assert(isfield(data, "i") && isfield(data, "v") && isfield(data, "t"), ...
    "SimuVerity:ReferenceSetup:DatasetFields", ...
    "The nominal XBATT-06 flight dataset is incomplete.");

mp.j = index;
mp.i = double(data.i(:));
mp.v = double(data.v(:));
mp.t = double(data.t(:));
mp.i(~isfinite(mp.i)) = 0;
valid = isfinite(mp.t) & isfinite(mp.v);
mp.i = mp.i(valid);
mp.v = mp.v(valid);
mp.t = mp.t(valid);
mp.t = mp.t - mp.t(1);
[mp.t, uniqueIndex] = unique(mp.t, "stable");
mp.i = mp.i(uniqueIndex);
mp.v = mp.v(uniqueIndex);
assert(numel(mp.t) >= 100 && mp.t(end) > 100, ...
    "SimuVerity:ReferenceSetup:DatasetDuration", ...
    "The nominal XBATT-06 flight dataset is too short.");

mp.Em0 = max(mp.v);
mp.SOC_0 = interp1(mp.Em, mp.SOC_LUT, mp.Em0, "linear", "extrap");
mp.SOC_0 = min(1, max(0, mp.SOC_0));
mp.CapacityAh = double(xhat(index, 1));
mp.CapacityAhPrime = mp.CapacityAh * ones(1, 2);
mp.InitialChargeDeficitAh = double(xhat(index, 2)) * ...
    (1 - mp.SOC_0) * mp.CapacityAh;
mp.itest = mp.i;
mp.tstop = mp.t(end);
mp.PLOT = 0;
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
