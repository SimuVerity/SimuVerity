function f90_xaero07_reference_clean_replay_setup(taskId, officialScenariosPath)
%F90_XAERO07_REFERENCE_CLEAN_REPLAY_SETUP Initialize the exact reference workspace.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XAERO-07", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XAERO-07.");
subject = string(getenv("SIMUVERITY_EVALUATION_SUBJECT"));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The native XAERO-07 workspace may only initialize the sealed reference.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
document = jsondecode(fileread(officialScenariosPath));
assert(isfield(document, "task_id") && string(document.task_id) == taskId && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 5, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XAERO-07 requires its exact five-scenario contract.");

assetRoot = string(pwd);
modelPath = fullfile(assetRoot, "ssc_aircraft_elec.slx");
scriptRoot = fullfile(assetRoot, "Scripts_Data");
configPath = fullfile(scriptRoot, "ssc_aircraft_elec_configs.m");
defaultsPath = fullfile(scriptRoot, "ssc_aircraft_elec_default_params.m");
localAssertAsset(modelPath, ...
    "present");
localAssertAsset(configPath, ...
    "present");
localAssertAsset(defaultsPath, ...
    "present");
addpath(assetRoot, scriptRoot, fullfile(assetRoot, "Libraries"), "-begin");
evalin("base", "run('" + replace(configPath, "'", "''") + "')");
evalin("base", "run('" + replace(defaultsPath, "'", "''") + "')");
assert(evalin("base", "exist('FlightProfileStruct','var') == 1") && ...
    evalin("base", "exist('FlightProfileChoice','var') == 1"), ...
    "SimuVerity:ReferenceSetup:OfficialInitializationIncomplete", ...
    "The official XAERO-07 initialization did not define its flight profile.");
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled XAERO-07 asset is missing or changed: %s", pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
