function f90_xmed07_reference_clean_replay_setup(taskId, officialScenariosPath, model)
%f90_xmed07_reference_clean_replay_setup Reference-only initialization.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end

assert(taskId == "F90-XMED-07", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMED-07.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The XMED-07 setup may initialize only the exact reference.");
assert(model == "InfusionPumpModelV7" && bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelIdentity", ...
    "XMED-07 compatibility setup requires the loaded exact reference alias.");

% The evaluator copies the sealed bundle with the required candidate alias
% at its root and the native entrypoint under src/Models.  That deliberate
% duplicate makes recursive filename discovery ambiguous; bind the exact
% reference paths instead.
runtimeRoot = string(pwd);
candidateAlias = fullfile(runtimeRoot, "InfusionPumpModelV7.slx");
referenceModel = fullfile(runtimeRoot, "src", "Models", ...
    "InfusionPumpModelV7.slx");
initPath = fullfile(runtimeRoot, "src", "Data", ...
    "InitializationInsulinPump.m");
softwareModel = fullfile(runtimeRoot, "src", "Models", "Controller", ...
    "InfusionPumpSoftwareModel.slx");
assert(isfile(candidateAlias) && isfile(referenceModel) && ...
    isfile(initPath) && isfile(softwareModel), ...
    "SimuVerity:ReferenceSetup:AssetClosureMissing", ...
    "The exact XMED-07 initialization/model closure is incomplete.");
assert(localFileIdentity(candidateAlias) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:ReferenceHash", ...
    "The clean replay is not using the exact XMED-07 reference model.");
assert(localFileIdentity(referenceModel) == localFileIdentity(candidateAlias), ...
    "SimuVerity:ReferenceSetup:AliasMismatch", ...
    "The root candidate alias is not the exact native XMED-07 reference.");

modelsRoot = fileparts(referenceModel);
controllerRoot = fullfile(modelsRoot, "Controller");
plantRoot = fullfile(modelsRoot, "Plant");
dataRoot = fileparts(initPath);
addpath(modelsRoot, "-begin");
addpath(controllerRoot, "-begin");
addpath(plantRoot, "-begin");
addpath(dataRoot, "-begin");
initLiteral = replace(initPath, "'", "''");
evalin("base", "run('" + initLiteral + "')");
load_system(fullfile(controllerRoot, "MotorController.slx"));
localApplyR2025aLookupCompatibility;
end

function localApplyR2025aLookupCompatibility
% The pinned PI-gain tables are constant at every breakpoint.  R2025a
% turns the original range-protection optimization into an assertion; disable
% only that optimization in memory after proving the table semantics.
blocks = [ ...
    "MotorController/FeedbackController/one_D_Lookup_Table"
    "MotorController/FeedbackController/one_D_Lookup_Table1"];
for index = 1:numel(blocks)
    assert(getSimulinkBlockHandle(blocks(index), false) > 0, ...
        "SimuVerity:ReferenceSetup:CompatibilityBlock", ...
        "Expected XMED-07 PI-gain lookup is missing: %s", blocks(index));
    rawTable = string(get_param(blocks(index), "Table"));
    values = evalin("base", char(rawTable));
    assert(~isempty(values) && all(isfinite(values)) && ...
        max(abs(values(:) - values(1))) <= eps(max(1, abs(values(1)))), ...
        "SimuVerity:ReferenceSetup:CompatibilitySemantic", ...
        "XMED-07 PI-gain lookup is not constant: %s", blocks(index));
    assert(abs(double(values(1)) - 5e-4) <= eps(5e-4), ...
        "SimuVerity:ReferenceSetup:CompatibilityValue", ...
        "XMED-07 PI-gain compatibility value differs from the pinned reference.");
    set_param(blocks(index), "RemoveProtectionInput", "off");
end
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
