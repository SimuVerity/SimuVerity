function f90_xbatt04_reference_clean_replay_setup( ...
        taskId, officialScenariosPath, model)
%F90_XBATT04_REFERENCE_CLEAN_REPLAY_SETUP Reset stale source operating point.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
    model (1,1) string
end
assert(taskId == "F90-XBATT-04", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XBATT-04.");
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The exact current XBATT-04 official scenarios are required.");
document = jsondecode(fileread(officialScenariosPath));
expectedIds = ["nominal", "cold_charge", "warm_cycle", ...
    "higher_charge_rate", "lower_upper_cutoff", ...
    "raised_lower_cutoff", "moderate_cold_rate"];
assert(string(document.task_id) == "F90-XBATT-04" && ...
    isfield(document, "scenarios") && numel(document.scenarios) == 7 && ...
    isequal(string({document.scenarios.id}), expectedIds), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The XBATT-04 scenario identity or ordering differs.");

assert(model == "TSPMeA_Cycling" && bdIsLoaded(model), ...
    "SimuVerity:ReferenceSetup:ModelNotLoaded", ...
    "The exact TSPMeA_Cycling reference alias must already be loaded.");
modelPath = string(get_param(model, "FileName"));
expectedModelBinding = ...
    "present";
assert(isfile(modelPath) && localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceIdentity", ...
    "The loaded model is not the current XBATT-04 reference.");
assert(string(get_param(model, "SimscapeUseOperatingPoints")) == "on" && ...
    string(get_param(model, "SimscapeOperatingPoint")) == "op", ...
    "SimuVerity:ReferenceSetup:OperatingPointContract", ...
    "The current reference no longer has the expected stale operating-point binding.");

set_param(model, "SimscapeUseOperatingPoints", "off");
evalin("base", "clear op");
assert(string(get_param(model, "SimscapeUseOperatingPoints")) == "off", ...
    "SimuVerity:ReferenceSetup:OperatingPointNotDisabled", ...
    "The stale Simscape operating-point reuse was not disabled in memory.");
assert(localFileIdentity(modelPath) == expectedModelBinding, ...
    "SimuVerity:ReferenceSetup:ReferenceModified", ...
    "Resetting operating-point reuse changed the sealed reference file.");
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
