function f90_xmed09_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xmed09_reference_clean_replay_setup Initialize the exact CVS-LVAD reference.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XMED-09", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMED-09.");
subject = lower(strtrim(string(getenv("SIMUVERITY_EVALUATION_SUBJECT"))));
assert(subject == "reference", ...
    "SimuVerity:ReferenceSetup:SubjectMismatch", ...
    "The native CVS-LVAD workspace may only initialize the exact reference.");

expectedScenarioBinding = ...
    "present";
assert(isfile(officialScenariosPath) && ...
    localFileIdentity(officialScenariosPath) == expectedScenarioBinding, ...
    "SimuVerity:ReferenceSetup:ScenarioIdentity", ...
    "The official XMED-09 scenario contract is missing or changed.");
document = jsondecode(fileread(officialScenariosPath));
scenarios = document.scenarios;
if iscell(scenarios), scenarios = [scenarios{:}]; end
expectedIds = ["nominal_impaired_sliding", "healthy_assisted", ...
    "impaired_unassisted", "pid_assist", "baroreflex_disabled", ...
    "fixed_resistance_elastance"];
assert(isstruct(document) && isscalar(document) && ...
    string(document.task_id) == taskId && ...
    numel(scenarios) == numel(expectedIds) && ...
    isequal(string({scenarios.id}), expectedIds) && ...
    isfield(document, "simulation"), ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "XMED-09 requires its exact ordered six-scenario contract.");
simulation = document.simulation;
assert(double(simulation.stop_time_s) == 60.0 && ...
    double(simulation.sample_time_s) == 0.001 && ...
    double(simulation.evidence_points) == 1501, ...
    "SimuVerity:ReferenceSetup:ScenarioContract", ...
    "The XMED-09 simulation contract is missing or changed.");
scenario = scenarios(1);
publicNames = ["CardiacConditionMode", "LVADConnected", ...
    "AssistControllerMode", "BaroreflexEnabled", ...
    "ResistanceVariationEnabled", "ElastanceVariationEnabled"];
assert(string(scenario.id) == "nominal_impaired_sliding" && ...
    string(scenario.class) == "nominal", ...
    "SimuVerity:ReferenceSetup:NominalScenarioMismatch", ...
    "The source-authoritative nominal XMED-09 scenario changed.");
for index = 1:numel(publicNames)
    name = char(publicNames(index));
    assert(isfield(scenario, name) && ...
        isnumeric(scenario.(name)) && isscalar(scenario.(name)) && ...
        double(scenario.(name)) == 1, ...
        "SimuVerity:ReferenceSetup:NominalScenarioMismatch", ...
        "The nominal XMED-09 mode %s must remain one.", name);
end

% Bundled validation stages the retained closure below source/ and an exact
% root alias for generic clean replay.  Bind both copies and run only the
% source-owned initializer from this fresh runtime submission.
assetRoot = string(pwd);
candidateAlias = fullfile(assetRoot, "CVS_LVAD_2021a.slx");
sourceModel = fullfile(assetRoot, "source", "CVS_LVAD_2021a.slx");
initializer = fullfile(assetRoot, "source", "SimMDL_Parameters.m");
expectedModelBinding = ...
    "present";
expectedInitializerBinding = ...
    "present";
localAssertAsset(candidateAlias, expectedModelBinding);
localAssertAsset(sourceModel, expectedModelBinding);
localAssertAsset(initializer, expectedInitializerBinding);

command = "run('" + replace(string(initializer), "'", "''") + "')";
evalin("base", command);

% SimMDL_Parameters starts with `clear all`, which removes the public nominal
% variables installed by the generic helper.  Restore only those six values
% from the repository-bundled first official scenario; no model parameter is changed.
for index = 1:numel(publicNames)
    assignin("base", char(publicNames(index)), ...
        double(scenario.(char(publicNames(index)))));
end

requiredVariables = ["dt_step", "end_t", "T", "n", "HR", "Tc", ...
    "Elvmax", "psai0", "tune_lambda1", "tune_lambda2", ...
    "tune_gamma", "tune_nu", "tune_alpha"];
for index = 1:numel(requiredVariables)
    assert(evalin("base", "exist('" + requiredVariables(index) + ...
        "','var') == 1"), ...
        "SimuVerity:ReferenceSetup:OfficialInitializationIncomplete", ...
        "The official XMED-09 initializer did not define %s.", ...
        requiredVariables(index));
end
dtStep = double(evalin("base", "dt_step"));
endTime = double(evalin("base", "end_t"));
time = double(evalin("base", "T"));
sampleCount = double(evalin("base", "n"));
heartRate = double(evalin("base", "HR"));
cardiacPeriod = double(evalin("base", "Tc"));
psai0 = double(evalin("base", "psai0"));
elvmax = double(evalin("base", "Elvmax"));
tuning = [double(evalin("base", "tune_lambda1")), ...
    double(evalin("base", "tune_lambda2")), ...
    double(evalin("base", "tune_gamma")), ...
    double(evalin("base", "tune_nu")), ...
    double(evalin("base", "tune_alpha"))];
assert(isscalar(dtStep) && dtStep == 0.001 && ...
    isscalar(endTime) && endTime == 60 && ...
    isvector(time) && numel(time) == 60001 && ...
    time(1) == 0 && time(end) == 60 && all(isfinite(time)) && ...
    all(diff(time) > 0) && sampleCount == numel(time) && ...
    heartRate == 130 && cardiacPeriod == 60 / 130 && ...
    psai0 == 75 && elvmax == 28.4 && ...
    isequal(tuning, [2.80726784416043, 0.849989015326732, ...
        14.8336742411938, 10.4274455916650, 0.708430135156437]), ...
    "SimuVerity:ReferenceSetup:OfficialInitializationIncomplete", ...
    "The official XMED-09 initializer produced an invalid workspace.");

localAssertAsset(candidateAlias, expectedModelBinding);
localAssertAsset(sourceModel, expectedModelBinding);
localAssertAsset(initializer, expectedInitializerBinding);
end

function localAssertAsset(pathValue, expectedBinding)
assert(isfile(pathValue) && localFileIdentity(pathValue) == expectedBinding, ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "A repository-bundled XMED-09 asset is missing or changed: %s", pathValue);
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
