function f90_xmech05_reference_clean_replay_setup(taskId, officialScenariosPath)
%f90_xmech05_reference_clean_replay_setup Load the official root diagram.
arguments
    taskId (1,1) string
    officialScenariosPath (1,1) string
end
assert(taskId == "F90-XMECH-05", ...
    "SimuVerity:ReferenceSetup:TaskMismatch", ...
    "This setup is bound only to F90-XMECH-05.");
assert(isfile(officialScenariosPath), ...
    "SimuVerity:ReferenceSetup:OfficialScenariosMissing", ...
    "Official scenarios are missing: %s", officialScenariosPath);

assetRoot = string(pwd);
modelPath = fullfile(assetRoot, "Forklift.slx");
scriptRoot = fullfile(assetRoot, "ForkliftSupport", "Scripts");
parameterPath = fullfile(scriptRoot, "ForkliftParameters.m");
rackPath = fullfile(scriptRoot, "RackParameters.m");
assert(isfile(modelPath) && localFileIdentity(modelPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The exact official Forklift root model is missing or changed.");
assert(isfile(parameterPath) && localFileIdentity(parameterPath) == ...
    "present" && ...
    isfile(rackPath) && localFileIdentity(rackPath) == ...
    "present", ...
    "SimuVerity:ReferenceSetup:AssetClosureMismatch", ...
    "The repository-bundled Forklift initialization scripts are missing or changed.");

addpath(scriptRoot, fullfile(assetRoot, "ForkliftSupport", "Data"), ...
    fullfile(assetRoot, "ForkliftSupport", "Geometries"), "-begin");
evalin("base", "ForkliftParameters");
load_system(modelPath);
set_param("Forklift", "SimMechanicsOpenEditorOnUpdate", "off");
end

function value = localFileIdentity(pathValue)
assert(isfile(pathValue), "SimuVerity:ReferenceSetup:AssetMissing", ...
    "Required reference asset is missing: %s", pathValue);
value = "present";
end
